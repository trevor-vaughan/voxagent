// TestSshkeyTargetChange: target is a property; its setter marks the old and
// the new target, so the record moves from one file to the other.
func TestSshkeyTargetChange(t *testing.T) {
	from := seedTarget(t, "mv ssh-rsa MMMM\nstay ssh-rsa SSSS\n")
	to := filepath.Join(t.TempDir(), "known_hosts")
	hh := newHarness("3.1.0")
	out := hh.apply(t, context.Background(), false,
		keyAt("stay@ssh-rsa", from, map[string]any{"key": "SSSS"}),
		keyAt("mv@ssh-rsa", to, map[string]any{"key": "MMMM"}))
	checkChanges(t, "stay", out[0].changes, nil, "")
	checkChanges(t, "mv", out[1].changes, []wantChange{{prop: "target", msg: "target changed '" + from + "' to '" + to + "'",
		was: from, is: to, wasShow: "'" + from + "'", isShow: "'" + to + "'"}}, "")
	if got := readTarget(t, from); got != header+"stay ssh-rsa SSSS\n" {
		t.Errorf("from = %q", got)
	}
	if got := readTarget(t, to); got != header+"mv ssh-rsa MMMM\n" {
		t.Errorf("to = %q", got)
	}
}

// runKeys applies a catalog of Sshkeys through the transaction, so the report
// shows what the transaction makes of Apply's results.
func runKeys(t *testing.T, ctx context.Context, s Sshkey, rs ...catalog.Resource) *report.Report {
	t.Helper()
	cat := &catalog.Catalog{Resources: rs}
	tx := &transaction.Transaction{Registry: ral.NewRegistry(s)}
	g, err := transaction.BuildGraph(ctx, cat, tx.Registry)
	if err != nil {
		t.Fatal(err)
	}
	rep := report.New("n", "production", false)
	if err := tx.Run(ctx, cat, g, rep); err != nil {
		t.Fatal(err)
	}
	return rep
}

func logLines(rep *report.Report) []string {
	var out []string
	for _, l := range rep.Logs {
		if l.Level != "debug" {
			out = append(out, l.Level+" "+l.Source+": "+l.Message)
		}
	}
	return out
}

// TestSshkeyEventNames pins the report's event names for property changes
// (key_changed, host_aliases_changed) and their array values (07b).
func TestSshkeyEventNames(t *testing.T) {
	target := seedTarget(t, "k,a1,a2 ssh-rsa AAAA\n")
	rep := runKeys(t, context.Background(), newHarness("3.1.0").s, keyAt("k@ssh-rsa", target, map[string]any{"key": "BBBB", "host_aliases": []any{"a2", "a1"}}))
	ev := rep.ResourceStatuses["Sshkey[k@ssh-rsa]"].Events
	if len(ev) != 2 || *ev[0].Name != "key_changed" || *ev[1].Name != "host_aliases_changed" ||
		!reflect.DeepEqual(ev[1].PreviousValue, []string{"a1", "a2"}) || !reflect.DeepEqual(ev[1].DesiredValue, []string{"a2", "a1"}) {
		t.Errorf("events = %+v", ev)
	}
}

// TestSshkeyCreateWithoutType is M7 07c-notype: validation passes, created is
// logged, then the flush fails with the engine's mandatory-field text as a
// resource_error; the target is not written (a backup of an existing one
// happens first, as in Ruby).
func TestSshkeyCreateWithoutType(t *testing.T) {
	const seed = "other ssh-rsa OOOO\n"
	target := seedTarget(t, seed)
	hh := newHarness("3.1.0")
	r := keyAt("foo", target, map[string]any{"key": "A"})
	if err := hh.s.Validate(r); err != nil {
		t.Fatalf("Validate: %v", err)
	}
	rep := runKeys(t, context.Background(), hh.s, r)
	st, ok := rep.ResourceStatuses["Sshkey[foo@]"]
	if !ok || !st.Failed || len(st.Events) != 2 {
		t.Fatalf("statuses = %+v", rep.ResourceStatuses)
	}
	ev := st.Events
	if ev[0].Message != "created" || *ev[0].Name != "sshkey_created" || ev[0].Status != "success" ||
		ev[1].Message != "Field 'type' is required" || *ev[1].Name != "resource_error" || ev[1].Property != nil || ev[1].Status != "failure" {
		t.Errorf("events = %+v %+v", ev[0], ev[1])
	}
	var found bool
	for _, l := range rep.Logs {
		if l.Level == "err" && l.Source == "/Sshkey[foo@]" && l.Message == "Could not evaluate: Field 'type' is required" {
			found = true
		}
	}
	if !found {
		t.Errorf("logs = %q", logLines(rep))
	}
	if got := readTarget(t, target); got != seed || len(hh.relabels) != 0 || !reflect.DeepEqual(hh.backups, []string{target}) {
		t.Errorf("file %q, backups %q, relabels %q", got, hh.backups, hh.relabels)
	}
}

// TestSshkeyMissingDirectory is M4 04s-nodir: the flat write fails, logged once
// by the filetype with source Puppet, then returned as the flush error and
// reported on the resource as Could not evaluate; nothing is created.
func TestSshkeyMissingDirectory(t *testing.T) {
	target := filepath.Join(t.TempDir(), "nonexistent", "kh")
	text := "Puppet::Util::FileType::FileTypeFlat could not write " + target + ": No such file or directory @ rb_sysopen - " + target
	r := keyAt("foo@ssh-rsa", target, map[string]any{"key": "A"})

	ctx, logs := raltest.DebugContext("debug")
	out := newHarness("3.1.0").apply(t, ctx, false, r)[0]
	var fe *ral.FlushError
	if !errors.As(out.err, &fe) || out.err.Error() != text || len(out.changes) != 1 {
		t.Errorf("changes %+v, err %v", out.changes, out.err)
	}
	var errs []string
	for _, l := range *logs {
		if l.Level == "err" {
			errs = append(errs, l.Source+": "+l.Message)
		}
	}
	if !reflect.DeepEqual(errs, []string{"Puppet: " + text}) {
		t.Errorf("err logs = %q", errs)
	}

	rep := runKeys(t, context.Background(), newHarness("3.1.0").s, r)
	st := rep.ResourceStatuses["Sshkey[foo@ssh-rsa]"]
	if !st.Failed || len(st.Events) != 2 || st.Events[0].Message != "created" || *st.Events[1].Name != "resource_error" || st.Events[1].Message != text {
		t.Errorf("status = %+v", st)
	}
	var found bool
	for _, l := range logLines(rep) {
		found = found || l == "err /Sshkey[foo@ssh-rsa]: Could not evaluate: "+text
	}
	if !found {
		t.Errorf("logs = %q", logLines(rep))
	}
	if _, err := os.Stat(filepath.Dir(target)); !os.IsNotExist(err) {
		t.Errorf("directory created: %v", err)
	}
}

// TestSshkeyPrefetchLeadingWhitespace is M7 07e-leadws: one line with leading
// whitespace aborts the prefetch, and every Sshkey is skipped.
func TestSshkeyPrefetchLeadingWhitespace(t *testing.T) {
	const seed = "good ssh-rsa GGGG\n lead ssh-rsa LLLL\n"
	target := seedTarget(t, seed)
	hh := newHarness("3.1.0")
	rep := runKeys(t, context.Background(), hh.s, keyAt("good@ssh-rsa", target, map[string]any{"key": "G2"}), keyAt("other@ssh-rsa", target, map[string]any{"key": "O"}))
	want := "err Puppet: Could not prefetch sshkey provider 'parsed': undefined method `split' for :absent:Symbol"
	if got := logLines(rep); len(got) == 0 || got[0] != want {
		t.Errorf("logs = %q, want first %q", got, want)
	}
	for _, ref := range []string{"Sshkey[good@ssh-rsa]", "Sshkey[other@ssh-rsa]"} {
		st, ok := rep.ResourceStatuses[ref]
		if !ok || !st.Failed || !st.Skipped || len(st.Events) != 1 || st.Events[0].Message != "Prefetch failed for sshkey provider 'parsed'" {
			t.Errorf("%s = %+v", ref, st)
		}
	}
	if got := readTarget(t, target); got != seed || len(hh.backups) != 0 {
		t.Errorf("file %q, backups %q", got, hh.backups)
	}
}

// TestSshkeySensitiveKey is spec 6: the transaction redacts a Sensitive key's
// change, values and message; a create shows no value.
func TestSshkeySensitiveKey(t *testing.T) {
	target := seedTarget(t, "k ssh-rsa OLDSECRET\n")
	hh := newHarness("3.1.0")
	change := keyAt("k@ssh-rsa", target, map[string]any{"key": "D8SECRET-new"})
	change.SensitiveParameters = []string{"key"}
	create := keyAt("c@ssh-rsa", target, map[string]any{"key": "D8SECRET-create"})
	create.SensitiveParameters = []string{"key"}
	rep := runKeys(t, context.Background(), hh.s, change, create)
	ev := rep.ResourceStatuses["Sshkey[k@ssh-rsa]"].Events
	if len(ev) != 1 || ev[0].Message != "changed [redacted] to [redacted]" || ev[0].PreviousValue != "[redacted]" ||
		ev[0].DesiredValue != "[redacted]" || ev[0].Redacted != true {
		t.Errorf("events = %+v", ev)
	}
	for _, l := range logLines(rep) {
		if strings.Contains(l, "SECRET") {
			t.Errorf("log leaks: %q", l)
		}
	}
	if got := readTarget(t, target); !strings.Contains(got, "k ssh-rsa D8SECRET-new\n") {
		t.Errorf("file = %q", got)
	}
}

// TestSshkeyNewFileMode is M4 04s-new and 17g-umask-*: a new known_hosts is
// 0644 & ~umask; an existing one keeps its mode and inode.
func TestSshkeyNewFileMode(t *testing.T) {
	for _, tc := range []struct {
		umask int
		want  os.FileMode
	}{{0o022, 0o644}, {0o027, 0o640}, {0o077, 0o600}, {0o000, 0o644}} {
		old := syscall.Umask(tc.umask)
		target := filepath.Join(t.TempDir(), "kh")
		hh := newHarness("3.1.0")
		out := hh.apply(t, context.Background(), false, keyAt("n@ssh-rsa", target, map[string]any{"key": "A"}))
		syscall.Umask(old)
		if out[0].err != nil {
			t.Fatal(out[0].err)
		}
		st, err := os.Stat(target)
		if err != nil {
			t.Fatal(err)
		}
		if st.Mode().Perm() != tc.want || len(hh.backups) != 0 {
			t.Errorf("umask %03o: mode %o, want %o; backups %q", tc.umask, st.Mode().Perm(), tc.want, hh.backups)
		}
		if got := readTarget(t, target); got != header+"n ssh-rsa A\n" {
			t.Errorf("file = %q", got)
		}
	}

	target := seedTarget(t, "k ssh-rsa A\n")
	if err := os.Chmod(target, 0o600); err != nil {
		t.Fatal(err)
	}
	before, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	hh := newHarness("3.1.0")
	hh.apply(t, context.Background(), false, keyAt("k@ssh-rsa", target, map[string]any{"key": "B"}))
	after, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if !os.SameFile(before, after) || after.Mode().Perm() != 0o600 {
		t.Errorf("same inode %v, mode %o", os.SameFile(before, after), after.Mode().Perm())
	}
}

// TestSshkeyBackupFailure: a failed backup fails the flush, and the target is
// not written.
func TestSshkeyBackupFailure(t *testing.T) {
	target := seedTarget(t, "k ssh-rsa A\n")
	s := newSshkey("3.1.0", "UTF-8", func(context.Context, string) error { return errors.New("bucket full") },
		func(context.Context, string) error { return nil })
	s.now = fixedNow
	r := keyAt("k@ssh-rsa", target, map[string]any{"key": "B"})
	primed, err := s.Prefetch(context.Background(), []catalog.Resource{r})
	if err != nil {
		t.Fatal(err)
	}
	changes, _, err := primed.Apply(atResource(context.Background(), r), r, false)
	var fe *ral.FlushError
	if len(changes) != 1 || !errors.As(err, &fe) || fe.Err.Error() != "bucket full" {
		t.Errorf("changes %+v, err %v", changes, err)
	}
	if got := readTarget(t, target); got != "k ssh-rsa A\n" {
		t.Errorf("file = %q", got)
	}
}

// TestSshkeyInSync: host_aliases is in sync only on exact list equality, and an
// :absent current is never in sync with a string (property.rb
// property_matches?), the empty string included.
func TestSshkeyInSync(t *testing.T) {
	list := func(l ...string) parsedfile.Value { return parsedfile.Value{Kind: parsedfile.List, L: l} }
	absent := parsedfile.Value{Kind: parsedfile.Absent}
	str := func(s string) parsedfile.Value { return parsedfile.Value{Kind: parsedfile.Str, S: s} }
	for _, tc := range []struct {
		prop       string
		is, should parsedfile.Value
		want       bool
	}{
		{"host_aliases", list("a", "b"), list("a", "b"), true},
		{"host_aliases", list(), list(), true},
		{"host_aliases", list("a", "b"), list("b", "a"), false},
		{"host_aliases", list("a"), list("a", "b"), false},
		{"host_aliases", absent, list(), false},
		{"key", str("K"), str("K"), true},
		{"key", str("K"), str("k"), false},
		{"key", absent, str(""), false},
	} {
		if got := inSync(tc.prop, tc.is, tc.should); got != tc.want {
			t.Errorf("inSync(%s, %+v, %+v) = %v", tc.prop, tc.is, tc.should, got)
		}
	}
}
