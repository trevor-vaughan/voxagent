var fixedNow = func() time.Time { return time.Date(2026, 11, 22, 3, 4, 5, 0, time.UTC) }

// header is the header every write under fixedNow starts with (M4).
const header = "# HEADER: This file was autogenerated at 2026-11-22 03:04:05 +0000\n" +
	"# HEADER: by puppet.  While it can still be managed manually, it\n" +
	"# HEADER: is definitely not recommended.\n"

// harness is a Sshkey whose flat hooks record the paths they were called with,
// on fixedNow. Every test resource names its target in a temp dir; the default
// target /etc/ssh/ssh_known_hosts is never touched.
type harness struct {
	s                 Sshkey
	backups, relabels []string
}

func newHarness(release string) *harness {
	hh := &harness{}
	hh.s = newSshkey(release, "UTF-8",
		func(_ context.Context, path string) error { hh.backups = append(hh.backups, path); return nil },
		func(_ context.Context, path string) error { hh.relabels = append(hh.relabels, path); return nil })
	hh.s.now = fixedNow
	return hh
}

func seedTarget(t *testing.T, text string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "known_hosts")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func readTarget(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// keyAt is a Sshkey resource on target; its title carries name and type.
func keyAt(title, target string, params map[string]any) catalog.Resource {
	p := map[string]any{"target": target}
	for k, v := range params {
		p[k] = v
	}
	return catalog.Resource{Type: "Sshkey", Title: title, Parameters: p}
}

// atResource is ctx carrying the sources the transaction gives r's Apply.
func atResource(ctx context.Context, r catalog.Resource) context.Context {
	return sources.WithSources(ctx, sources.Sources{Resource: "/Stage[main]/Main/" + r.Ref(), Ref: r.Ref()})
}

type outcome struct {
	changes []ral.Change
	err     error
}

// apply prefetches rs and applies each in order, as the walk does.
func (hh *harness) apply(t *testing.T, ctx context.Context, noop bool, rs ...catalog.Resource) []outcome {
	t.Helper()
	primed, err := hh.s.Prefetch(ctx, rs)
	if err != nil {
		t.Fatalf("Prefetch: %v", err)
	}
	var out []outcome
	for _, r := range rs {
		changes, warnings, err := primed.Apply(atResource(ctx, r), r, noop)
		if len(warnings) != 0 {
			t.Errorf("%s: warnings %v", r.Ref(), warnings)
		}
		out = append(out, outcome{changes, err})
	}
	return out
}

// wantChange is a change's fields a test pins.
type wantChange struct {
	prop, msg, name string
	was, is         any
	wasShow, isShow string
}

func checkChanges(t *testing.T, ref string, got []ral.Change, want []wantChange, suffix string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%s: changes = %+v, want %d", ref, got, len(want))
	}
	for i, w := range want {
		g := got[i]
		if g.Property != w.prop || g.Message != w.msg+suffix || g.Name != w.name ||
			!reflect.DeepEqual(g.Was, w.was) || !reflect.DeepEqual(g.Is, w.is) {
			t.Errorf("%s: change %d = {%s %q %q %#v %#v}, want {%s %q %q %#v %#v}", ref, i,
				g.Property, g.Message, g.Name, g.Was, g.Is, w.prop, w.msg+suffix, w.name, w.was, w.is)
		}
		if w.prop != "ensure" && (!g.DisplayVerbatim || g.WasDisplay != w.wasShow || g.IsDisplay != w.isShow) {
			t.Errorf("%s: change %d display = %v %q %q, want %q %q", ref, i, g.DisplayVerbatim, g.WasDisplay, g.IsDisplay, w.wasShow, w.isShow)
		}
	}
}

// seedMessages is 07b's known_hosts with 07f's tabs and trailing comment.
const seedMessages = "# my comment\n\nk1,a1,a2 ssh-rsa AAAA\nk2,a1,a2 ssh-rsa BBBB\nk3,a1,a2 ssh-rsa CCCC\n" +
	"k4 ssh-rsa DDDD\nk5 ssh-rsa EEEE\nk6\tssh-rsa\tTTTT\nk7 ssh-rsa GGGG # trailing comment\n"

// TestSshkeyApplyMessages is M7 07b, 07f and 06g-style noop: key and
// host_aliases messages with event values (host_aliases arrays both ways), a
// reorder out of sync, [] against none in sync, [] against aliases dropping
// the field, the comment-swallowing key, one flush per changed resource, one
// backup per prefetch; noop changes nothing.
func TestSshkeyApplyMessages(t *testing.T) {
	want := map[string][]wantChange{
		"k1@ssh-rsa": {{prop: "key", msg: "key changed 'AAAA' to 'AAAA2'", was: "AAAA", is: "AAAA2", wasShow: "'AAAA'", isShow: "'AAAA2'"}},
		"k2@ssh-rsa": {{prop: "host_aliases", msg: "host_aliases changed ['a1', 'a2'] to ['a2', 'a1']",
			was: []string{"a1", "a2"}, is: []string{"a2", "a1"}, wasShow: "['a1', 'a2']", isShow: "['a2', 'a1']"}},
		"k3@ssh-rsa": {{prop: "host_aliases", msg: "host_aliases changed ['a1', 'a2'] to []",
			was: []string{"a1", "a2"}, is: []string{}, wasShow: "['a1', 'a2']", isShow: "[]"}},
		"k4@ssh-rsa": {{prop: "host_aliases", msg: "host_aliases changed [] to ['a1', 'x']",
			was: []string{}, is: []string{"a1", "x"}, wasShow: "[]", isShow: "['a1', 'x']"}},
		"k5@ssh-rsa": nil,
		"k6@ssh-rsa": {{prop: "key", msg: "key changed 'TTTT' to 'T2'", was: "TTTT", is: "T2", wasShow: "'TTTT'", isShow: "'T2'"}},
		"k7@ssh-rsa": {{prop: "key", msg: "key changed 'GGGG # trailing comment' to 'GGGG'",
			was: "GGGG # trailing comment", is: "GGGG", wasShow: "'GGGG # trailing comment'", isShow: "'GGGG'"}},
	}
	for _, noop := range []bool{false, true} {
		target := seedTarget(t, seedMessages)
		rs := []catalog.Resource{
			keyAt("k1@ssh-rsa", target, map[string]any{"key": "AAAA2", "host_aliases": []any{"a1", "a2"}}),
			keyAt("k2@ssh-rsa", target, map[string]any{"key": "BBBB", "host_aliases": []any{"a2", "a1"}}),
			keyAt("k3@ssh-rsa", target, map[string]any{"key": "CCCC", "host_aliases": []any{}}),
			keyAt("k4@ssh-rsa", target, map[string]any{"key": "DDDD", "host_aliases": []any{"a1", "x"}}),
			keyAt("k5@ssh-rsa", target, map[string]any{"key": "EEEE", "host_aliases": []any{}}),
			keyAt("k6@ssh-rsa", target, map[string]any{"key": "T2"}),
			keyAt("k7@ssh-rsa", target, map[string]any{"key": "GGGG"}),
		}
		ctx, logs := raltest.DebugContext("debug")
		hh := newHarness("3.1.0")
		out := hh.apply(t, ctx, noop, rs...)
		suffix := ""
		if noop {
			suffix = " (noop)"
		}
		for i, r := range rs {
			if out[i].err != nil {
				t.Errorf("noop=%v %s: err %v", noop, r.Ref(), out[i].err)
			}
			checkChanges(t, r.Ref(), out[i].changes, want[r.Title], suffix)
		}
		flushes := strings.Count(strings.Join(raltest.LinesAt(*logs, "Puppet"), "\n"), "Flushing sshkey provider target "+target)
		if noop {
			if got := readTarget(t, target); got != seedMessages || flushes != 0 || len(hh.backups) != 0 || len(hh.relabels) != 0 {
				t.Errorf("noop: file %q, %d flushes, backups %q, relabels %q", got, flushes, hh.backups, hh.relabels)
			}
			continue
		}
		wantText := header + "# my comment\n\nk1,a1,a2 ssh-rsa AAAA2\nk2,a2,a1 ssh-rsa BBBB\nk3 ssh-rsa CCCC\n" +
			"k4,a1,x ssh-rsa DDDD\nk5 ssh-rsa EEEE\nk6 ssh-rsa T2\nk7 ssh-rsa GGGG\n"
		if got := readTarget(t, target); got != wantText {
			t.Errorf("file = %q, want %q", got, wantText)
		}
		if flushes != 6 || !reflect.DeepEqual(hh.backups, []string{target}) || len(hh.relabels) != 6 {
			t.Errorf("%d flushes, backups %q, relabels %q", flushes, hh.backups, hh.relabels)
		}
		if lines := raltest.LinesAt(*logs, "Puppet"); len(lines) == 0 || lines[0] != "Prefetching parsed resources for sshkey" {
			t.Errorf("Puppet debug = %q", lines)
		}

		// Rerun: in sync, nothing written.
		hh = newHarness("3.1.0")
		for _, o := range hh.apply(t, context.Background(), false, rs...) {
			if len(o.changes) != 0 || o.err != nil {
				t.Errorf("rerun: %+v", o)
			}
		}
		if len(hh.backups) != 0 || readTarget(t, target) != wantText {
			t.Errorf("rerun wrote: backups %q", hh.backups)
		}
	}
}

// TestSshkeyCreateRemove is M7 07a and 17b: created and removed with their
// events, [] on a create writes `name type key` with no alias field and no
// host_aliases event, ensure => absent on a missing key only a debug line, and
// ensure => absent without a type matches no record (nothing removed).
func TestSshkeyCreateRemove(t *testing.T) {
	const seed = "keep ssh-rsa KKKK\nold ssh-rsa OOOO\n"
	rs := func(target string) []catalog.Resource {
		return []catalog.Resource{
			keyAt("new1@ssh-rsa", target, map[string]any{"key": "NNNN", "host_aliases": []any{"n1", "new1"}}),
			keyAt("new2@ssh-ed25519", target, map[string]any{"key": "EEEE", "host_aliases": []any{}}),
			keyAt("old@ssh-rsa", target, map[string]any{"ensure": "absent"}),
			keyAt("ghost@ssh-rsa", target, map[string]any{"ensure": "absent"}),
			keyAt("keep", target, map[string]any{"ensure": "absent"}),
		}
	}
	for _, noop := range []bool{true, false} {
		target := seedTarget(t, seed)
		ctx, logs := raltest.DebugContext("debug")
		hh := newHarness("3.1.0")
		out := hh.apply(t, ctx, noop, rs(target)...)
		suffix := ""
		if noop {
			suffix = " (noop)"
		}
		checkChanges(t, "new1", out[0].changes, []wantChange{{prop: "ensure", msg: "created", name: "sshkey_created", was: "absent", is: "present"}}, suffix)
		checkChanges(t, "new2", out[1].changes, []wantChange{{prop: "ensure", msg: "created", name: "sshkey_created", was: "absent", is: "present"}}, suffix)
		checkChanges(t, "old", out[2].changes, []wantChange{{prop: "ensure", msg: "removed", name: "sshkey_removed", was: "present", is: "absent"}}, suffix)
		checkChanges(t, "ghost", out[3].changes, nil, suffix)
		checkChanges(t, "keep", out[4].changes, nil, suffix)
		for _, ref := range []string{"Sshkey[ghost@ssh-rsa]"} {
			if got := raltest.LinesAt(*logs, "/Stage[main]/Main/"+ref); !reflect.DeepEqual(got, []string{"Nothing to manage: no ensure and the resource doesn't exist"}) {
				t.Errorf("%s debug = %q", ref, got)
			}
		}
		for _, o := range out {
			if o.err != nil {
				t.Errorf("err %v", o.err)
			}
		}
		if noop {
			if len(hh.backups) != 0 || readTarget(t, target) != seed {
				t.Errorf("noop wrote: backups %q", hh.backups)
			}
			continue
		}
		if got, want := readTarget(t, target), header+"keep ssh-rsa KKKK\nnew1,n1,new1 ssh-rsa NNNN\nnew2 ssh-ed25519 EEEE\n"; got != want {
			t.Errorf("file = %q, want %q", got, want)
		}
	}
}

// TestSshkeyLineBreakKeyWritten is M13 13a-sshkey-key (spec §8 item 16, I-39):
// under 2.5.0 a key holding a line break is written verbatim, so it adds a
// line; the next run parses that line as a record of its own, finds the key
// changed and appends the injected line again.
func TestSshkeyLineBreakKeyWritten(t *testing.T) {
	const key = "AAAA\nBBBB ssh-rsa CCCC"
	target := seedTarget(t, "# seed\n")
	r := keyAt("h.example@ssh-rsa", target, map[string]any{"key": key})
	ctx, _ := raltest.DebugContext("debug")

	out := newHarness("2.5.0").apply(t, ctx, false, r)
	if out[0].err != nil {
		t.Fatalf("first run: %v", out[0].err)
	}
	checkChanges(t, "first run", out[0].changes, []wantChange{{prop: "ensure", msg: "created", name: "sshkey_created", was: "absent", is: "present"}}, "")
	if got, want := readTarget(t, target), header+"# seed\nh.example ssh-rsa AAAA\nBBBB ssh-rsa CCCC\n"; got != want {
		t.Fatalf("first run file = %q, want %q", got, want)
	}

	out = newHarness("2.5.0").apply(t, ctx, false, r)
	if out[0].err != nil {
		t.Fatalf("second run: %v", out[0].err)
	}
	checkChanges(t, "second run", out[0].changes, []wantChange{{prop: "key", msg: `key changed 'AAAA' to "AAAA\nBBBB ssh-rsa CCCC"`,
		was: "AAAA", is: key, wasShow: "'AAAA'", isShow: `"AAAA\nBBBB ssh-rsa CCCC"`}}, "")
	if got, want := readTarget(t, target), header+"# seed\nh.example ssh-rsa AAAA\nBBBB ssh-rsa CCCC\nBBBB ssh-rsa CCCC\n"; got != want {
		t.Errorf("second run file = %q, want %q", got, want)
	}
}

