// tagged is a Ruby value as testdata/munge.rb records it.
type tagged struct {
	Kind  string          `json:"kind"`
	Value json.RawMessage `json:"value"`
}

type mungeRow struct {
	Param   string            `json:"param"`
	Params  map[string]tagged `json:"params"`
	Munged  *tagged           `json:"munged"`
	Inspect string            `json:"inspect"`
	Error   *string           `json:"error"`
}

type mungeCorpus struct {
	OpenVox      string     `json:"openvox"`
	ScriptSHA256 string     `json:"script_sha256"`
	Rows         []mungeRow `json:"rows"`
}

func loadMungeCorpus(t *testing.T) mungeCorpus {
	t.Helper()
	data, err := os.ReadFile("testdata/munge.json")
	if err != nil {
		t.Fatal(err)
	}
	var c mungeCorpus
	if err := json.Unmarshal(data, &c); err != nil {
		t.Fatal(err)
	}
	return c
}

// catalogValue is the value the catalog decoder hands a unit for v: Integers
// and Floats as float64, Arrays as []any.
func catalogValue(t *testing.T, v tagged) any {
	t.Helper()
	switch v.Kind {
	case "Boolean":
		var b bool
		mustUnmarshal(t, v.Value, &b)
		return b
	case "String":
		var s string
		mustUnmarshal(t, v.Value, &s)
		return s
	case "Integer":
		var s string
		mustUnmarshal(t, v.Value, &s)
		n, err := strconv.ParseInt(s, 10, 64)
		if err != nil {
			t.Fatalf("Integer input %s: %v", s, err)
		}
		return float64(n)
	case "Float":
		var f float64
		mustUnmarshal(t, v.Value, &f)
		return f
	case "Array":
		var elems []tagged
		mustUnmarshal(t, v.Value, &elems)
		out := make([]any, len(elems))
		for i, e := range elems {
			out[i] = catalogValue(t, e)
		}
		return out
	}
	t.Fatalf("input kind %q", v.Kind)
	return nil
}

func mustUnmarshal(t *testing.T, data []byte, dst any) {
	t.Helper()
	if err := json.Unmarshal(data, dst); err != nil {
		t.Fatal(err)
	}
}

// rubyInt is a munged Integer, which may be a Bignum.
func rubyInt(t *testing.T, v tagged) *big.Int {
	t.Helper()
	var s string
	mustUnmarshal(t, v.Value, &s)
	n, ok := new(big.Int).SetString(s, 10)
	if !ok {
		t.Fatalf("munged Integer %q", s)
	}
	return n
}

// saturate clamps n into [math.MinInt64, limit].
func saturate(n *big.Int, limit int64) int64 {
	if n.Cmp(big.NewInt(limit)) > 0 {
		return limit
	}
	return n.Int64()
}

// rowResource is the catalog resource Ruby built for row: the path is the
// title, as a catalog Tidy without a path parameter carries it.
func rowResource(t *testing.T, row mungeRow) catalog.Resource {
	t.Helper()
	r := catalog.Resource{Type: "Tidy", Parameters: map[string]any{}}
	for name, v := range row.Params {
		if name == "path" {
			r.Title = catalogValue(t, v).(string)
			continue
		}
		r.Parameters[name] = catalogValue(t, v)
	}
	return r
}

// hasLineBreak reports whether any String in v, at any depth, holds a "\n".
func hasLineBreak(v any) bool {
	switch v := v.(type) {
	case string:
		return strings.Contains(v, "\n")
	case []any:
		for _, e := range v {
			if hasLineBreak(e) {
				return true
			}
		}
	}
	return false
}

// hasNonString reports whether the flattened Array v holds a non-String.
func hasNonString(v any) bool {
	switch v := v.(type) {
	case string:
		return false
	case []any:
		for _, e := range v {
			if hasNonString(e) {
				return true
			}
		}
		return false
	}
	return true
}

// wantDelegated is spec §0's "Delegate, not native" row, read off the corpus
// row: the conditions are stated on Ruby's inputs and results, not on the
// parser's code.
func wantDelegated(r catalog.Resource, row mungeRow) bool {
	if row.Param == "path" && (!strings.HasPrefix(r.Title, "/") || strings.HasPrefix(r.Title, "//")) {
		return true
	}
	if row.Error != nil && row.Param == "size" && strings.Contains(*row.Error, "undefined local variable or method `age'") {
		return true
	}
	for _, v := range r.Parameters {
		if hasLineBreak(v) {
			return true
		}
	}
	if m, ok := r.Parameters["matches"]; ok && hasNonString(m) {
		return true
	}
	return false
}

func TestMungeCorpusIsCurrent(t *testing.T) {
	c := loadMungeCorpus(t)
	if c.OpenVox != "8.34.0" {
		t.Errorf("corpus generated by openvox %q, want 8.34.0; rerun testdata/munge.sh", c.OpenVox)
	}
	script, err := os.ReadFile("testdata/munge.rb")
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(script)
	if got := hex.EncodeToString(sum[:]); got != c.ScriptSHA256 {
		t.Errorf("munge.json was generated by munge.rb %s, the file is %s; rerun testdata/munge.sh", c.ScriptSHA256, got)
	}
	if len(c.Rows) == 0 {
		t.Fatal("corpus has no rows")
	}
}

func TestParseParamsMatchesRuby(t *testing.T) {
	for _, row := range loadMungeCorpus(t).Rows {
		r := rowResource(t, row)
		name := row.Param + " " + rowName(row.Params)
		t.Run(name, func(t *testing.T) {
			reason := delegateReason(r)
			if wantDelegated(r, row) {
				if reason == "" {
					t.Fatalf("native, want delegated (Ruby: %s%s)", row.Inspect, deref(row.Error))
				}
				return
			}
			if reason != "" {
				t.Fatalf("delegated (%s), want native", reason)
			}
			p, err := parseParams(r)
			if row.Error != nil {
				if err == nil {
					t.Fatalf("parsed %+v, want refusal %q", p, *row.Error)
				}
				if err.Error() != *row.Error {
					t.Fatalf("refusal\n got %q\nwant %q", err.Error(), *row.Error)
				}
				return
			}
			if err != nil {
				t.Fatalf("refused %q, want %s", err, row.Inspect)
			}
			checkMunged(t, row, p)
		})
	}
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

// rowName names a corpus row by its inputs.
func rowName(params map[string]tagged) string {
	b, _ := json.Marshal(params)
	return string(b)
}

// checkMunged compares the parsed field for row.Param with Ruby's munged
// value; Integers saturate (spec §3.1).
func checkMunged(t *testing.T, row mungeRow, p params) {
	t.Helper()
	m := *row.Munged
	var got, want any
	switch row.Param {
	case "path":
		got, want = p.Path, catalogString(t, m)
	case "recurse":
		got = p.Recurse
		switch m.Kind {
		case "nil":
			want = (*int)(nil)
		case "Boolean":
			if string(m.Value) == "true" {
				n := math.MaxInt
				want = &n
			} else {
				want = (*int)(nil)
			}
		case "Integer":
			n := int(saturate(rubyInt(t, m), math.MaxInt))
			want = &n
		}
	case "max_files":
		got = p.MaxFiles
		switch m.Kind {
		case "Integer":
			want = saturate(rubyInt(t, m), math.MaxInt64)
		case "String":
			want = catalogString(t, m)
		}
	case "matches":
		got = p.Matches
		if m.Kind == "nil" {
			want = []string(nil)
		} else {
			var elems []tagged
			mustUnmarshal(t, m.Value, &elems)
			ws := []string{}
			for _, e := range elems {
				ws = append(ws, catalogString(t, e))
			}
			want = ws
		}
	case "backup":
		return
	case "age", "size":
		got = p.Age
		if row.Param == "size" {
			got = p.Size
		}
		want = (*int64)(nil)
		if m.Kind == "Integer" {
			n := saturate(rubyInt(t, m), math.MaxInt64)
			want = &n
		}
	case "type":
		got, want = p.TimeField, catalogString(t, m)
	case "rmdirs":
		got, want = p.RmDirs, m.Kind == "Boolean" && string(m.Value) == "true"
	default:
		t.Fatalf("corpus parameter %q", row.Param)
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("%s munged to %s; got %s, want %s", row.Param, row.Inspect, show(got), show(want))
	}
}

func catalogString(t *testing.T, v tagged) string {
	t.Helper()
	if v.Kind != "String" && v.Kind != "Symbol" {
		t.Fatalf("munged %s, want a String or Symbol", v.Kind)
	}
	var s string
	mustUnmarshal(t, v.Value, &s)
	return s
}

func show(v any) string {
	switch v := v.(type) {
	case *int:
		if v != nil {
			return strconv.Itoa(*v)
		}
	case *int64:
		if v != nil {
			return strconv.FormatInt(*v, 10)
		}
	}
	b, _ := json.Marshal(v)
	return string(b)
}

func TestDelegateReason(t *testing.T) {
	rich := map[string]any{"__ptype": "Deferred", "name": "x"}
	delegated := []struct {
		name   string
		title  string
		params map[string]any
	}{
		{"relative path", "t/rel", nil},
		{"home path", "~/x", nil},
		{"double slash", "//tmp/x", nil},
		{"triple slash", "///tmp/x", nil},
		{"relative path parameter", "/x", map[string]any{"path": "t/rel"}},
		{"non-String path", "/x", map[string]any{"path": float64(5)}},
		{"Integer size", "/x", map[string]any{"size": float64(10)}},
		{"Boolean size", "/x", map[string]any{"size": true}},
		{"Array size", "/x", map[string]any{"size": []any{"1k"}}},
		{"unmatched size", "/x", map[string]any{"size": "abc"}},
		{"empty size", "/x", map[string]any{"size": ""}},
		{"line break in age", "/x", map[string]any{"age": "1d\n"}},
		{"line break in size", "/x", map[string]any{"size": "1k\nx"}},
		{"line break in recurse", "/x", map[string]any{"recurse": "1\n"}},
		{"line break in max_files", "/x", map[string]any{"recurse": true, "max_files": "5\n"}},
		{"line break in type", "/x", map[string]any{"type": "atime\n"}},
		{"line break in a matches element", "/x", map[string]any{"recurse": true, "matches": []any{"a", "b\n"}}},
		{"non-String matches element", "/x", map[string]any{"recurse": true, "matches": []any{float64(1)}}},
		{"nested non-String matches element", "/x", map[string]any{"recurse": true, "matches": []any{[]any{true}}}},
		{"non-String matches", "/x", map[string]any{"recurse": true, "matches": float64(1)}},
		{"rich value", "/x", map[string]any{"age": rich}},
		{"Hash value", "/x", map[string]any{"type": map[string]any{"a": "b"}}},
		{"Hash in an Array", "/x", map[string]any{"age": []any{map[string]any{"a": "b"}}}},
		{"Integer beyond a float's precision", "/x", map[string]any{"recurse": float64(1 << 60)}},
	}
	for _, c := range delegated {
		t.Run(c.name, func(t *testing.T) {
			r := catalog.Resource{Type: "Tidy", Title: c.title, Parameters: c.params}
			if got := delegateReason(r); got == "" {
				t.Errorf("native, want delegated")
			}
			if _, err := parseParams(r); err == nil {
				t.Errorf("parseParams accepted a delegated Tidy")
			}
		})
	}

	native := []struct {
		name     string
		title    string
		params   map[string]any
		wantPath string
	}{
		{"cleaned path parameter", "t", map[string]any{"path": "/tmp//t/../t/"}, "/tmp/t"},
		{"root", "/", nil, "/"},
		{"title", "/var/tmp/", nil, "/var/tmp"},
		{"undef path falls back to the title", "/x", map[string]any{"path": nil}, "/x"},
		{"carriage return in age is Ruby's refusal", "/x", map[string]any{"age": "1d\r"}, ""},
		{"line break in rmdirs is Ruby's refusal", "/x", map[string]any{"rmdirs": "true\n"}, ""},
		{"backup of any shape", "/x", map[string]any{"backup": []any{float64(1)}}, "/x"},
	}
	for _, c := range native {
		t.Run(c.name, func(t *testing.T) {
			r := catalog.Resource{Type: "Tidy", Title: c.title, Parameters: c.params}
			if got := delegateReason(r); got != "" {
				t.Fatalf("delegated (%s), want native", got)
			}
			p, err := parseParams(r)
			if c.wantPath == "" {
				if err == nil {
					t.Errorf("accepted, want Ruby's refusal")
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if p.Path != c.wantPath {
				t.Errorf("path %q, want %q", p.Path, c.wantPath)
			}
		})
	}
}

func TestParseParamsDefaults(t *testing.T) {
	p, err := parseParams(catalog.Resource{Type: "Tidy", Title: "/x"})
	if err != nil {
		t.Fatal(err)
	}
	want := params{Path: "/x", MaxFiles: int64(0), TimeField: "atime"}
	if !reflect.DeepEqual(p, want) {
		t.Errorf("got %+v, want %+v", p, want)
	}
}

// TestParseParamsRubyOrder: Ruby sets the parameters in declaration order
// (type.rb:2446, TY:24-226), so the first refused one is the one reported.
func TestParseParamsRubyOrder(t *testing.T) {
	r := catalog.Resource{Type: "Tidy", Title: "/x", Parameters: map[string]any{
		"rmdirs": "on", "type": "bogus", "age": "1x", "max_files": "x", "recurse": "yes",
	}}
	_, err := parseParams(r)
	if err == nil || !strings.HasPrefix(err.Error(), "Parameter recurse failed") {
		t.Errorf("got %v, want recurse's refusal first", err)
	}
}

func TestRefusalRedactsSensitive(t *testing.T) {
	cases := []struct {
		name   string
		params map[string]any
		want   string
	}{
		{"age unit", map[string]any{"age": "10"}, "Parameter age failed on Tidy[/x]: Invalid age unit [redacted]"},
		{"age", map[string]any{"age": "abc"}, "Parameter age failed on Tidy[/x]: Invalid tidy age [redacted]"},
		{"age Integer()", map[string]any{"age": "08d"}, "Parameter age failed on Tidy[/x]: Munging failed for value [redacted] in class age: invalid value for Integer(): [redacted]"},
		{"size unit", map[string]any{"size": "1x"}, "Parameter size failed on Tidy[/x]: Invalid size unit [redacted]"},
		{"recurse", map[string]any{"recurse": "yes"}, "Parameter recurse failed on Tidy[/x]: Munging failed for value [redacted] in class recurse: Invalid recurse value [redacted]"},
		{"max_files", map[string]any{"max_files": "x"}, "Parameter max_files failed on Tidy[/x]: Invalid value [redacted]. Valid values match /^[0-9]+$/."},
		{"type", map[string]any{"type": "bogus"}, "Parameter type failed on Tidy[/x]: Invalid value [redacted]. Valid values are atime, mtime, ctime."},
		{"rmdirs", map[string]any{"rmdirs": "on"}, "Parameter rmdirs failed on Tidy[/x]: Invalid value [redacted]. Valid values are true, false, yes, no."},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			var marked []string
			for name := range c.params {
				marked = append(marked, name)
			}
			r := catalog.Resource{Type: "Tidy", Title: "/x", Parameters: c.params, SensitiveParameters: marked}
			_, err := parseParams(r)
			if err == nil || err.Error() != c.want {
				t.Errorf("got %v\nwant %s", err, c.want)
			}
		})
	}
	r := catalog.Resource{Type: "Tidy", Title: "/a\x00b", Parameters: map[string]any{"path": "/a\x00b"}, SensitiveParameters: []string{"path"}}
	if _, err := parseParams(r); err == nil || strings.Contains(err.Error(), "for value \"") {
		t.Errorf("path refusal %v, want the value redacted", err)
	}
}
