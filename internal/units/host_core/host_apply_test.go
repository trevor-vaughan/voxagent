var fixedNow = func() time.Time { return time.Date(2026, 11, 22, 3, 4, 5, 0, time.UTC) }

// hostHeader is the header every write under fixedNow starts with (M4).
const hostHeader = "# HEADER: This file was autogenerated at 2026-11-22 03:04:05 +0000\n" +
	"# HEADER: by puppet.  While it can still be managed manually, it\n" +
	"# HEADER: is definitely not recommended.\n"

// hostHarness is a Host whose flat hooks record the paths they were called
// with, on fixedNow. Every test resource names its target in a temp dir; the
// default target /etc/hosts is only read.
type hostHarness struct {
	h                 Host
	backups, relabels []string
}

func newHostHarness() *hostHarness {
	hh := &hostHarness{}
	hh.h = newHost("UTF-8",
		func(_ context.Context, path string) error { hh.backups = append(hh.backups, path); return nil },
		func(_ context.Context, path string) error { hh.relabels = append(hh.relabels, path); return nil })
	hh.h.now = fixedNow
	return hh
}

// seedTarget writes text to a new file in a temp dir and returns its path.
func seedTarget(t *testing.T, text string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "hosts")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func readTarget(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// hostAt is a Host resource on target.
func hostAt(title, target string, params map[string]any) catalog.Resource {
	p := map[string]any{"target": target}
	for k, v := range params {
		p[k] = v
	}
	return catalog.Resource{Type: "Host", Title: title, Parameters: p}
}

// atResource is ctx carrying the sources the transaction gives r's Apply.
func atResource(ctx context.Context, r catalog.Resource) context.Context {
	return sources.WithSources(ctx, sources.Sources{Resource: "/Stage[main]/Main/" + r.Ref(), Ref: r.Ref()})
}

type hostOutcome struct {
	changes []ral.Change
	err     error
}

// apply prefetches rs and applies each in order, as the walk does.
func (hh *hostHarness) apply(t *testing.T, ctx context.Context, noop bool, rs ...catalog.Resource) []hostOutcome {
	t.Helper()
	primed, err := hh.h.Prefetch(ctx, rs)
	if err != nil {
		t.Fatalf("Prefetch: %v", err)
	}
	var out []hostOutcome
	for _, r := range rs {
		changes, warnings, err := primed.Apply(atResource(ctx, r), r, noop)
		if len(warnings) != 0 {
			t.Errorf("%s: warnings %v", r.Ref(), warnings)
		}
		out = append(out, hostOutcome{changes, err})
	}
	return out
}

// wantChange is a change's fields a test pins.
type wantChange struct {
	prop, msg, name string
	was, is         any
	wasShow, isShow string
}

func checkChanges(t *testing.T, ref string, got []ral.Change, want []wantChange, suffix string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%s: changes = %+v, want %d", ref, got, len(want))
	}
	for i, w := range want {
		g := got[i]
		if g.Property != w.prop || g.Message != w.msg+suffix || g.Name != w.name ||
			!reflect.DeepEqual(g.Was, w.was) || !reflect.DeepEqual(g.Is, w.is) {
			t.Errorf("%s: change %d = {%s %q %q %#v %#v}, want {%s %q %q %#v %#v}", ref, i,
				g.Property, g.Message, g.Name, g.Was, g.Is, w.prop, w.msg+suffix, w.name, w.was, w.is)
		}
		if w.prop != "ensure" && (!g.DisplayVerbatim || g.WasDisplay != w.wasShow || g.IsDisplay != w.isShow) {
			t.Errorf("%s: change %d display = %v %q %q, want %q %q", ref, i, g.DisplayVerbatim, g.WasDisplay, g.IsDisplay, w.wasShow, w.isShow)
		}
	}
}

// seedChanges is 06b's /etc/hosts.
const seedChanges = "127.0.0.1\tlocalhost\n192.0.2.1\th1 a b c # c1\n192.0.2.2\th2 x y\n192.0.2.3\th3 p # c3\n" +
	"192.0.2.4\th4 q\n192.0.2.5\th5 r # gone\n"

// TestHostApplyMessages is M6 06b and 06g: every property message, the event
// values (host_aliases: previous an array, desired the joined string), one
// flush per changed resource and one backup per prefetch; noop changes nothing.
func TestHostApplyMessages(t *testing.T) {
	want := map[string][]wantChange{
		"h1": {{prop: "ip", msg: "ip changed '192.0.2.1' to '192.0.2.99'", was: "192.0.2.1", is: "192.0.2.99", wasShow: "'192.0.2.1'", isShow: "'192.0.2.99'"}},
		"h2": {{prop: "host_aliases", msg: "host_aliases changed x y to 'y x'", was: []string{"x", "y"}, is: "y x", wasShow: "x y", isShow: "'y x'"}},
		"h3": {{prop: "comment", msg: "comment changed 'c3' to 'c3-new'", was: "c3", is: "c3-new", wasShow: "'c3'", isShow: "'c3-new'"}},
		"h4": {{prop: "comment", msg: "comment changed '' to 'added'", was: "", is: "added", wasShow: "''", isShow: "'added'"}},
		"h5": {{prop: "comment", msg: "comment changed 'gone' to ''", was: "gone", is: "", wasShow: "'gone'", isShow: "''"}},
	}
	for _, noop := range []bool{false, true} {
		target := seedTarget(t, seedChanges)
		rs := []catalog.Resource{
			hostAt("h1", target, map[string]any{"ip": "192.0.2.99", "host_aliases": []any{"a", "b", "c"}, "comment": "c1"}),
			hostAt("h2", target, map[string]any{"ip": "192.0.2.2", "host_aliases": []any{"y", "x"}}),
			hostAt("h3", target, map[string]any{"ip": "192.0.2.3", "host_aliases": []any{"p"}, "comment": "c3-new"}),
			hostAt("h4", target, map[string]any{"ip": "192.0.2.4", "host_aliases": []any{"q"}, "comment": "added"}),
			hostAt("h5", target, map[string]any{"ip": "192.0.2.5", "host_aliases": []any{"r"}, "comment": ""}),
		}
		ctx, logs := raltest.DebugContext("debug")
		hh := newHostHarness()
		out := hh.apply(t, ctx, noop, rs...)
		suffix := ""
		if noop {
			suffix = " (noop)"
		}
		for i, r := range rs {
			if out[i].err != nil {
				t.Errorf("noop=%v %s: err %v", noop, r.Ref(), out[i].err)
			}
			checkChanges(t, r.Ref(), out[i].changes, want[r.Title], suffix)
		}
		flushes := strings.Count(strings.Join(raltest.LinesAt(*logs, "Puppet"), "\n"), "Flushing host provider target "+target)
		if noop {
			if got := readTarget(t, target); got != seedChanges || flushes != 0 || len(hh.backups) != 0 || len(hh.relabels) != 0 {
				t.Errorf("noop: file %q, %d flushes, backups %q, relabels %q", got, flushes, hh.backups, hh.relabels)
			}
			continue
		}
		wantText := hostHeader + "127.0.0.1\tlocalhost\n192.0.2.99\th1\ta b c\t# c1\n192.0.2.2\th2\ty x\n" +
			"192.0.2.3\th3\tp\t# c3-new\n192.0.2.4\th4\tq\t# added\n192.0.2.5\th5\tr\n"
		if got := readTarget(t, target); got != wantText {
			t.Errorf("file = %q, want %q", got, wantText)
		}
		if flushes != 5 || !reflect.DeepEqual(hh.backups, []string{target}) || len(hh.relabels) != 5 {
			t.Errorf("%d flushes, backups %q, relabels %q", flushes, hh.backups, hh.relabels)
		}
		if lines := raltest.LinesAt(*logs, "Puppet"); len(lines) == 0 || lines[0] != "Prefetching parsed resources for host" {
			t.Errorf("Puppet debug = %q", lines)
		}

		// Rerun: in sync, nothing written.
		hh = newHostHarness()
		for _, o := range hh.apply(t, context.Background(), false, rs...) {
			if len(o.changes) != 0 || o.err != nil {
				t.Errorf("rerun: %+v", o)
			}
		}
		if len(hh.backups) != 0 || readTarget(t, target) != wantText {
			t.Errorf("rerun wrote: backups %q", hh.backups)
		}
	}
}

// TestHostAliasesEmpty is M6 06c and spec 8 item 2: [] writes ip<TAB>name<TAB>
// and is in sync afterwards and with no aliases; the reread aliases are
// absent, so a later list is `defined`.
func TestHostAliasesEmpty(t *testing.T) {
	target := seedTarget(t, "192.0.2.1\th1 a b\n192.0.2.2\th2 a b # c2\n192.0.2.3\th3\n")
	empty := map[string]any{"host_aliases": []any{}}
	rs := []catalog.Resource{hostAt("h1", target, empty), hostAt("h2", target, empty), hostAt("h3", target, empty)}
	hh := newHostHarness()
	out := hh.apply(t, context.Background(), false, rs...)
	checkChanges(t, "Host[h1]", out[0].changes, []wantChange{{prop: "host_aliases", msg: "host_aliases changed a b to ''",
		was: []string{"a", "b"}, is: "", wasShow: "a b", isShow: "''"}}, "")
	checkChanges(t, "Host[h2]", out[1].changes, []wantChange{{prop: "host_aliases", msg: "host_aliases changed a b to ''",
		was: []string{"a", "b"}, is: "", wasShow: "a b", isShow: "''"}}, "")
	checkChanges(t, "Host[h3]", out[2].changes, nil, "")
	written := hostHeader + "192.0.2.1\th1\t\n192.0.2.2\th2\t\t# c2\n192.0.2.3\th3\n"
	if got := readTarget(t, target); got != written {
		t.Fatalf("file = %q, want %q", got, written)
	}

	hh = newHostHarness()
	for i, o := range hh.apply(t, context.Background(), false, rs...) {
		if len(o.changes) != 0 || o.err != nil {
			t.Errorf("rerun %s: %+v", rs[i].Ref(), o)
		}
	}
	if got := readTarget(t, target); got != written || len(hh.backups) != 0 {
		t.Errorf("rerun wrote %q, backups %q", got, hh.backups)
	}

	hh = newHostHarness()
	out = hh.apply(t, context.Background(), false, hostAt("h1", target, map[string]any{"host_aliases": []any{"a"}}),
		hostAt("h2", target, map[string]any{"host_aliases": []any{"x"}, "comment": "c2"}))
	checkChanges(t, "Host[h1]", out[0].changes, []wantChange{{prop: "host_aliases", msg: "defined 'host_aliases' as 'a'",
		was: "absent", is: "a", wasShow: "absent", isShow: "'a'"}}, "")
	checkChanges(t, "Host[h2]", out[1].changes, []wantChange{{prop: "host_aliases", msg: "defined 'host_aliases' as 'x'",
		was: "absent", is: "x", wasShow: "absent", isShow: "'x'"}}, "")
	if got, want := readTarget(t, target), hostHeader+"192.0.2.1\th1\ta\n192.0.2.2\th2\tx\t# c2\n192.0.2.3\th3\n"; got != want {
		t.Errorf("file = %q, want %q", got, want)
	}
}

// TestHostCreateRemove is M6 06a: created and removed with their events, the
// new line appended, and ensure => absent on a missing host only a debug line.
func TestHostCreateRemove(t *testing.T) {
	target := seedTarget(t, "127.0.0.1\tlocalhost\n192.0.2.5\told.example\n")
	rs := []catalog.Resource{
		hostAt("new1.example", target, map[string]any{"ip": "192.0.2.1", "host_aliases": []any{"n1", "new1"}, "comment": "first"}),
		hostAt("old.example", target, map[string]any{"ensure": "absent"}),
		hostAt("ghost.example", target, map[string]any{"ensure": "absent"}),
	}
	for _, noop := range []bool{true, false} {
		ctx, logs := raltest.DebugContext("debug")
		hh := newHostHarness()
		out := hh.apply(t, ctx, noop, rs...)
		suffix := ""
		if noop {
			suffix = " (noop)"
		}
		checkChanges(t, "new1", out[0].changes, []wantChange{{prop: "ensure", msg: "created", name: "host_created", was: "absent", is: "present"}}, suffix)
		checkChanges(t, "old", out[1].changes, []wantChange{{prop: "ensure", msg: "removed", name: "host_removed", was: "present", is: "absent"}}, suffix)
		checkChanges(t, "ghost", out[2].changes, nil, suffix)
		if got := raltest.LinesAt(*logs, "/Stage[main]/Main/Host[ghost.example]"); !reflect.DeepEqual(got, []string{"Nothing to manage: no ensure and the resource doesn't exist"}) {
			t.Errorf("ghost debug = %q", got)
		}
		for _, o := range out {
			if o.err != nil {
				t.Errorf("err %v", o.err)
			}
		}
		if noop {
			if len(hh.backups) != 0 || readTarget(t, target) != "127.0.0.1\tlocalhost\n192.0.2.5\told.example\n" {
				t.Errorf("noop wrote: backups %q", hh.backups)
			}
			continue
		}
		if got, want := readTarget(t, target), hostHeader+"127.0.0.1\tlocalhost\n192.0.2.1\tnew1.example\tn1 new1\t# first\n"; got != want {
			t.Errorf("file = %q, want %q", got, want)
		}
	}
}

// TestHostPreservesLines is M4 04h-preserve: text lines kept byte-for-byte in
// place, parsed lines re-serialised, a hand-written # HEADER line dropped, the
// new host appended.
func TestHostPreservesLines(t *testing.T) {
	seed := "# my comment\n\n   \n\t# tab comment\n  indented line\nthis is not a host line\n192.0.2.3\nface\n" +
		"# HEADER fake\n192.0.2.1\th1  a   b   # trailing comment\ndead   beef  # x\n192.0.2.2 h2\n"
	target := seedTarget(t, seed)
	hh := newHostHarness()
	out := hh.apply(t, context.Background(), false, hostAt("h9", target, map[string]any{"ip": "192.0.2.9"}))
	if len(out[0].changes) != 1 || out[0].err != nil {
		t.Fatalf("outcome = %+v", out[0])
	}
	want := hostHeader + "# my comment\n\n   \n\t# tab comment\n  indented line\nthis is not a host line\n192.0.2.3\nface\n" +
		"192.0.2.1\th1\ta b\t# trailing comment\ndead\tbeef\t# x\n192.0.2.2\th2\n192.0.2.9\th9\n"
	if got := readTarget(t, target); got != want {
		t.Errorf("file = %q, want %q", got, want)
	}
}

// TestHostNewTarget is M4 04h-newtarget and M5: a missing target is created
// 0600 without a backup; the next run's change backs it up, once, and keeps
// its mode and inode.
func TestHostNewTarget(t *testing.T) {
	target := filepath.Join(t.TempDir(), "newhosts")
	r := hostAt("n.example", target, map[string]any{"ip": "192.0.2.1"})
	hh := newHostHarness()
	if out := hh.apply(t, context.Background(), false, r); out[0].err != nil {
		t.Fatal(out[0].err)
	}
	st, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if st.Mode().Perm() != 0o600 || len(hh.backups) != 0 || !reflect.DeepEqual(hh.relabels, []string{target}) {
		t.Errorf("mode %o, backups %q, relabels %q", st.Mode().Perm(), hh.backups, hh.relabels)
	}
	if got := readTarget(t, target); got != hostHeader+"192.0.2.1\tn.example\n" {
		t.Errorf("file = %q", got)
	}

	hh = newHostHarness()
	rs := []catalog.Resource{
		hostAt("n.example", target, map[string]any{"ip": "192.0.2.2"}),
		hostAt("m.example", target, map[string]any{"ip": "192.0.2.3"}),
	}
	for _, o := range hh.apply(t, context.Background(), false, rs...) {
		if len(o.changes) != 1 || o.err != nil {
			t.Errorf("outcome = %+v", o)
		}
	}
	st2, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(hh.backups, []string{target}) || !os.SameFile(st, st2) || st2.Mode().Perm() != 0o600 {
		t.Errorf("backups %q, same inode %v, mode %o", hh.backups, os.SameFile(st, st2), st2.Mode().Perm())
	}
}

// TestHostTargetChange: target is a property; its setter marks the old and the
// new target, so the record moves from one file to the other.
func TestHostTargetChange(t *testing.T) {
	from := seedTarget(t, "192.0.2.1\tmv.example\n192.0.2.2\tstay.example\n")
	to := filepath.Join(t.TempDir(), "hosts")
	hh := newHostHarness()
	out := hh.apply(t, context.Background(), false,
		hostAt("stay.example", from, map[string]any{"ip": "192.0.2.2"}),
		hostAt("mv.example", to, map[string]any{"ip": "192.0.2.1"}))
	checkChanges(t, "stay", out[0].changes, nil, "")
	checkChanges(t, "mv", out[1].changes, []wantChange{{prop: "target", msg: "target changed '" + from + "' to '" + to + "'",
		was: from, is: to, wasShow: "'" + from + "'", isShow: "'" + to + "'"}}, "")
	if got := readTarget(t, from); got != hostHeader+"192.0.2.2\tstay.example\n" {
		t.Errorf("from = %q", got)
	}
	if got := readTarget(t, to); got != hostHeader+"192.0.2.1\tmv.example\n" {
		t.Errorf("to = %q", got)
	}
}

// runHosts applies a catalog of Hosts through the transaction, so the report
// shows what the transaction makes of Apply's results.
func runHosts(t *testing.T, h Host, rs ...catalog.Resource) *report.Report {
	t.Helper()
	cat := &catalog.Catalog{Resources: rs}
	tx := &transaction.Transaction{Registry: ral.NewRegistry(h)}
	ctx := context.Background()
	g, err := transaction.BuildGraph(ctx, cat, tx.Registry)
	if err != nil {
		t.Fatal(err)
	}
	rep := report.New("n", "production", false)
	if err := tx.Run(ctx, cat, g, rep); err != nil {
		t.Fatal(err)
	}
	return rep
}

func logLines(rep *report.Report) []string {
	var out []string
	for _, l := range rep.Logs {
		if l.Level != "debug" {
			out = append(out, l.Level+" "+l.Source+": "+l.Message)
		}
	}
	return out
}

// TestHostCreateWithoutIP is M6 06e: validation passes, created is logged,
// then the flush fails with the ToLine text as a resource_error; the target is
// not written. The raw 06e console shows the backup (Computing checksum, the
// bucket lock) before the error: Ruby backs a target up before generating it.
func TestHostCreateWithoutIP(t *testing.T) {
	const seed = "127.0.0.1\tlocalhost\n"
	for _, params := range []map[string]any{
		{"host_aliases": []any{"z"}},
		{"ensure": "present"},
		{"ensure": "present", "comment": "c"},
	} {
		target := seedTarget(t, seed)
		hh := newHostHarness()
		r := hostAt("noip.example", target, params)
		if err := hh.h.Validate(r); err != nil {
			t.Fatalf("Validate: %v", err)
		}
		rep := runHosts(t, hh.h, r)
		st, ok := rep.ResourceStatuses["Host[noip.example]"]
		if !ok || !st.Failed || len(st.Events) != 2 {
			t.Fatalf("status = %+v", st)
		}
		ev := st.Events
		if ev[0].Message != "created" || *ev[0].Name != "host_created" || ev[0].Status != "success" ||
			ev[1].Message != "ip is a required attribute for hosts" || *ev[1].Name != "resource_error" || ev[1].Property != nil || ev[1].Status != "failure" {
			t.Errorf("events = %+v %+v", ev[0], ev[1])
		}
		var found bool
		for _, l := range rep.Logs {
			if l.Level == "err" && strings.HasSuffix(l.Source, "Host[noip.example]") && l.Message == "Could not evaluate: ip is a required attribute for hosts" {
				found = true
			}
		}
		if !found {
			t.Errorf("logs = %q", logLines(rep))
		}
		if got := readTarget(t, target); got != seed || len(hh.relabels) != 0 || !reflect.DeepEqual(hh.backups, []string{target}) {
			t.Errorf("file %q, backups %q, relabels %q", got, hh.backups, hh.relabels)
		}
	}
}

// TestHostPrefetchReadError is spec 5 intro: a flat read error aborts the
// type's prefetch and every Host is skipped.
func TestHostPrefetchReadError(t *testing.T) {
	dir := t.TempDir()
	hh := newHostHarness()
	rep := runHosts(t, hh.h, hostAt("a.example", dir, map[string]any{"ip": "192.0.2.1"}), hostAt("b.example", dir, map[string]any{"ip": "192.0.2.2"}))
	prefix := "err Puppet: Could not prefetch host provider 'parsed': "
	var found bool
	for _, l := range logLines(rep) {
		if strings.HasPrefix(l, prefix) && strings.Contains(l, "could not read "+dir+": ") {
			found = true
		}
	}
	if !found {
		t.Errorf("logs = %q", logLines(rep))
	}
	for _, ref := range []string{"Host[a.example]", "Host[b.example]"} {
		st, ok := rep.ResourceStatuses[ref]
		if !ok || !st.Failed || !st.Skipped || len(st.Events) != 1 || st.Events[0].Message != "Prefetch failed for host provider 'parsed'" {
			t.Errorf("%s = %+v", ref, st)
		}
	}
	if len(hh.backups) != 0 {
		t.Errorf("backups %q", hh.backups)
	}
}

// TestHostBackupFailure: a failed backup fails the flush, and the target is
// not written.
func TestHostBackupFailure(t *testing.T) {
	target := seedTarget(t, "192.0.2.1\th1\n")
	h := newHost("UTF-8", func(context.Context, string) error { return errors.New("bucket full") },
		func(context.Context, string) error { return nil })
	h.now = fixedNow
	r := hostAt("h1", target, map[string]any{"ip": "192.0.2.2"})
	primed, err := h.Prefetch(context.Background(), []catalog.Resource{r})
	if err != nil {
		t.Fatal(err)
	}
	changes, _, err := primed.Apply(atResource(context.Background(), r), r, false)
	var fe *ral.FlushError
	if len(changes) != 1 || !errors.As(err, &fe) || fe.Err.Error() != "bucket full" {
		t.Errorf("changes %+v, err %v", changes, err)
	}
	if got := readTarget(t, target); got != "192.0.2.1\th1\n" {
		t.Errorf("file = %q", got)
	}
}

// TestHostPropertyChangeAbsent: an :absent current is never in sync with a
// string should, the empty string included (property.rb property_matches?),
// and is `defined`; for host_aliases it counts as [] (list:57-62).
func TestHostPropertyChangeAbsent(t *testing.T) {
	absent := parsedfile.Value{Kind: parsedfile.Absent}
	ch := propertyChange("comment", absent, parsedfile.Value{Kind: parsedfile.Str, S: ""})
	if ch == nil || ch.Message != "defined 'comment' as ''" || ch.Was != "absent" || ch.Is != "" {
		t.Errorf("comment = %+v", ch)
	}
	if ch := propertyChange("host_aliases", absent, parsedfile.Value{Kind: parsedfile.List}); ch != nil {
		t.Errorf("host_aliases [] = %+v, want in sync", ch)
	}
}
