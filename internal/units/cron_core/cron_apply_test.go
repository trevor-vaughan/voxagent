// TestCronCreateDestroy covers spec 6.2: create copies every should and
// appends the named job; destroy drops it; both rewrite the whole target.
func TestCronCreateDestroy(t *testing.T) {
	for _, release := range releases {
		t.Run(release, func(t *testing.T) {
			h := newCronHarness(t, release, map[string]string{"root": seedJ})
			h.applyCrons(t, context.Background(), false,
				cronCatRes("new", map[string]any{"command": "/x", "minute": []any{"5", "6"}, "weekday": "Tue", "environment": "A=1"}))
			want := cronHeader0 + seedJ + "# Puppet Name: new\nA=1\n5,6 * * * 2 /x\n"
			if len(h.tab.writes) != 1 || h.tab.writes[0] != (tabWrite{"root", want}) {
				t.Errorf("create wrote %q, want %q", h.tab.writes, want)
			}

			h = newCronHarness(t, release, map[string]string{"root": seedJ})
			h.applyCrons(t, context.Background(), false, cronCatRes("sp", map[string]any{"command": "", "special": "reboot"}))
			want = cronHeader0 + seedJ + "# Puppet Name: sp\n@reboot \n"
			if len(h.tab.writes) != 1 || h.tab.writes[0].text != want {
				t.Errorf("special create wrote %q, want %q", h.tab.writes, want)
			}

			h = newCronHarness(t, release, map[string]string{"root": seedJ})
			h.applyCrons(t, context.Background(), false, cronCatRes("j", map[string]any{"ensure": "absent"}))
			want = cronHeader0 + "# Puppet Name: k\nSHELL=/bin/sh\nMAILTO=x\n2 * * * * /bin/k\n"
			if len(h.tab.writes) != 1 || h.tab.writes[0] != (tabWrite{"root", want}) {
				t.Errorf("destroy wrote %q, want %q", h.tab.writes, want)
			}
		})
	}
}

