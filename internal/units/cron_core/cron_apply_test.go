// runCrons applies a catalog of Crons through the transaction, so the report
// shows what the transaction makes of Apply's results.
func runCrons(t *testing.T, c Cron, noop bool, rs ...catalog.Resource) *report.Report {
	t.Helper()
	cat := &catalog.Catalog{Resources: rs}
	tx := &transaction.Transaction{Registry: ral.NewRegistry(c), Noop: noop}
	ctx := context.Background()
	g, err := transaction.BuildGraph(ctx, cat, tx.Registry)
	if err != nil {
		t.Fatal(err)
	}
	rep := report.New("n", "production", noop)
	if err := tx.Run(ctx, cat, g, rep); err != nil {
		t.Fatal(err)
	}
	return rep
}

func logLines(rep *report.Report) []string {
	var out []string
	for _, l := range rep.Logs {
		if l.Level != "debug" {
			out = append(out, l.Level+" "+l.Source+": "+l.Message)
		}
	}
	return out
}

