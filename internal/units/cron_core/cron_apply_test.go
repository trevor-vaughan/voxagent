// crontabPath is the executable route resolution found; the fake runner sees it
// as the command name.
const crontabPath = "/usr/bin/crontab"

// cronHeader0 is the header every write under fixedNow starts with.
const cronHeader0 = "# HEADER: This file was autogenerated at 2026-11-22 03:04:05 +0000 by puppet.\n" +
	"# HEADER: While it can still be managed manually, it is definitely not recommended.\n" +
	"# HEADER: Note particularly that the comments starting with 'Puppet Name' should\n" +
	"# HEADER: not be deleted, as doing so could cause duplicate cron jobs.\n"

// tabReply is what fakeCrontab answers for one argument list.
type tabReply struct {
	code int
	out  string
	err  error
}

// tabWrite is one `crontab -` the fake received.
type tabWrite struct{ user, text string }

// fakeCrontab stands in for cronie's crontab. It keeps one text per user and
// answers -l from it, or `no crontab for <u>` on exit 1 as cronie does; a write
// installs its stdin and answers with echo(stdin). `crontab -l` without -u
// lists self's crontab. replies overrides the answer for "args joined by
// spaces".
type fakeCrontab struct {
	self    string
	tabs    map[string]string
	replies map[string]tabReply
	echo    func(stdin string) string
	calls   []string // name and args joined by spaces
	writes  []tabWrite
}

func (f *fakeCrontab) Run(_ context.Context, o command.ArgvOpts, name string, args ...string) (int, string, error) {
	f.calls = append(f.calls, strings.Join(append([]string{name}, args...), " "))
	if r, ok := f.replies[strings.Join(args, " ")]; ok {
		return r.code, r.out, r.err
	}
	user, tail := f.self, args[0]
	if args[0] == "-u" {
		user, tail = args[1], args[2]
	}
	if tail == "-" {
		f.writes = append(f.writes, tabWrite{user, string(o.Stdin)})
		f.tabs[user] = string(o.Stdin)
		if f.echo != nil {
			return 0, f.echo(string(o.Stdin)), nil
		}
		return 0, "", nil
	}
	if text, ok := f.tabs[user]; ok {
		return 0, text, nil
	}
	return 1, "no crontab for " + user + "\n", nil
}

// cronUsers is the fake passwd: root has the test's own uid, so its crontab is
// read with `crontab -l` as Ruby reads the invoker's; bin has uid 1, so the
// numeric target "1" resolves for Puppet.
func cronUsers() raltest.FakeNSS {
	return raltest.FakeNSS{Users: map[string]nameservice.PasswdEntry{
		"root": {Name: "root", UID: int64(os.Getuid())},
		"bin":  {Name: "bin", UID: 1},
		"llm":  {Name: "llm", UID: 70001},
	}}
}

// cronHarness is a Cron over a fake crontab, the fake passwd, an empty spool
// directory and fixedNow. Its environment has no USER, so the provider's
// default target is root.
type cronHarness struct {
	c   Cron
	tab *fakeCrontab
	ns  raltest.FakeNSS
	out *bytes.Buffer
}

func newCronHarness(t *testing.T, release string, tabs map[string]string) *cronHarness {
	t.Helper()
	tab := &fakeCrontab{self: "root", tabs: tabs, replies: map[string]tabReply{}}
	if tab.tabs == nil {
		tab.tabs = map[string]string{}
	}
	ns := cronUsers()
	out := &bytes.Buffer{}
	c := newCron(release, crontabPath, "UTF-8", func(string) (string, bool) { return "", false }, tab, ns, out)
	c.spoolDir = t.TempDir()
	c.now = fixedNow
	return &cronHarness{c: c, tab: tab, ns: ns, out: out}
}

func cronCatRes(title string, params map[string]any, marked ...string) catalog.Resource {
	return catalog.Resource{Type: "Cron", Title: title, Parameters: params, SensitiveParameters: marked}
}

// atResource is ctx carrying the sources the transaction gives r's Apply.
func atResource(ctx context.Context, r catalog.Resource) context.Context {
	return sources.WithSources(ctx, sources.Sources{Resource: "/Stage[main]/Main/" + r.Ref(), Ref: r.Ref()})
}

// cronOutcome is one resource's Apply result.
type cronOutcome struct {
	changes []ral.Change
	err     error
}

// applyCrons prefetches rs and applies each in order, as the walk does.
func (h *cronHarness) applyCrons(t *testing.T, ctx context.Context, noop bool, rs ...catalog.Resource) []cronOutcome {
	t.Helper()
	primed, err := h.c.Prefetch(ctx, rs)
	if err != nil {
		t.Fatalf("Prefetch: %v", err)
	}
	var out []cronOutcome
	for _, r := range rs {
		changes, warnings, err := primed.Apply(atResource(ctx, r), r, noop)
		if len(warnings) != 0 {
			t.Errorf("%s: warnings %v", r.Ref(), warnings)
		}
		out = append(out, cronOutcome{changes, err})
	}
	return out
}

func messages(changes []ral.Change) []string {
	var out []string
	for _, ch := range changes {
		out = append(out, ch.Message)
	}
	return out
}

// seedJ is root's crontab for the message cases: j has no environment lines,
// k has two.
const seedJ = "# Puppet Name: j\n15 * * * * $HOME/bin/monthly\n# Puppet Name: k\nSHELL=/bin/sh\nMAILTO=x\n2 * * * * /bin/k\n"

// TestCronApplyMessages covers every message form of spec 6.1, live and noop,
// with the event values and names; an ensure change syncs nothing else.
func TestCronApplyMessages(t *testing.T) {
	const cmd = "$HOME/bin/monthly"
	type change struct {
		prop, msg, name string
		was, is         any
	}
	for _, tc := range []struct {
		name     string
		releases []string
		title    string
		params   map[string]any
		want     []change
	}{
		{name: "created", title: "new", params: map[string]any{"command": "/x", "minute": "5", "hour": "3"},
			want: []change{{"ensure", "created", "cron_created", "absent", "present"}}},
		{name: "removed", title: "j", params: map[string]any{"ensure": "absent", "command": "/other"},
			want: []change{{"ensure", "removed", "cron_removed", "present", "absent"}}},
		{name: "command changed", title: "j", params: map[string]any{"command": "/x", "minute": "15"},
			want: []change{{"command", "command changed '$HOME/bin/monthly' to '/x'", "", cmd, "/x"}}},
		{name: "command quoting", title: "j", params: map[string]any{"command": "a\tb"},
			want: []change{{"command", `command changed '$HOME/bin/monthly' to "a\tb"`, "", cmd, "a\tb"}}},
		{name: "minute changed", title: "j", params: map[string]any{"command": cmd, "minute": "5"},
			want: []change{{"minute", "minute changed ['15'] to ['5']", "", []string{"15"}, []string{"5"}}}},
		{name: "minute order and padding", title: "j", params: map[string]any{"minute": []any{"15", "05"}},
			want: []change{{"minute", "minute changed ['15'] to ['15', '05']", "", []string{"15"}, []string{"15", "05"}}}},
		{name: "minute undefined", title: "j", params: map[string]any{"minute": "absent"},
			want: []change{{"minute", "undefined 'minute' from ['15']", "", []string{"15"}, "absent"}}},
		{name: "weekday defined", title: "j", params: map[string]any{"weekday": []any{"1", "3"}},
			want: []change{{"weekday", "defined 'weekday' as ['1', '3']", "", "absent", []string{"1", "3"}}}},
		{name: "special then minute", title: "j", params: map[string]any{"special": "weekly", "minute": "absent"},
			want: []change{
				{"special", "defined 'special' as 'weekly'", "", "absent", "weekly"},
				{"minute", "undefined 'minute' from ['15']", "", []string{"15"}, "absent"},
			}},
		{name: "environment none 1.3.0", releases: []string{"1.3.0"}, title: "j", params: map[string]any{"environment": "A=1"},
			want: []change{{"environment", "defined 'environment' as A=1", "", "absent", []string{"A=1"}}}},
		{name: "environment none 2.1.0", releases: []string{"2.1.0"}, title: "j", params: map[string]any{"environment": "A=1"},
			want: []change{{"environment", "environment changed [] to A=1", "", []string{}, []string{"A=1"}}}},
		{name: "environment list", title: "k", params: map[string]any{"environment": []any{"A=1", `B="x\y"`}},
			want: []change{{"environment", `environment changed ['SHELL=/bin/sh', 'MAILTO=x'] to A=1,B="x\y"`, "", []string{"SHELL=/bin/sh", "MAILTO=x"}, []string{"A=1", `B="x\y"`}}}},
		{name: "environment absent literal", title: "k", params: map[string]any{"environment": "absent"},
			want: []change{{"environment", "environment changed ['SHELL=/bin/sh', 'MAILTO=x'] to absent", "", []string{"SHELL=/bin/sh", "MAILTO=x"}, []string{"absent"}}}},
		{name: "environment sorted in sync", title: "k", params: map[string]any{"environment": []any{"MAILTO=x", "SHELL=/bin/sh"}}},
		{name: "user changed", title: "j", params: map[string]any{"user": "bin", "target": "root"},
			want: []change{{"user", "user changed 'root' to 'bin'", "", "root", "bin"}}},
		{name: "in sync", title: "j", params: map[string]any{"command": cmd, "minute": "15", "hour": "*", "user": "root"}},
	} {
		rels := tc.releases
		if rels == nil {
			rels = releases
		}
		for _, release := range rels {
			for _, noop := range []bool{false, true} {
				t.Run(fmt.Sprintf("%s/%s/noop=%v", tc.name, release, noop), func(t *testing.T) {
					h := newCronHarness(t, release, map[string]string{"root": seedJ})
					got := h.applyCrons(t, context.Background(), noop, cronCatRes(tc.title, tc.params))[0]
					if got.err != nil {
						t.Fatalf("Apply: %v", got.err)
					}
					if len(got.changes) != len(tc.want) {
						t.Fatalf("changes = %q, want %d", messages(got.changes), len(tc.want))
					}
					for i, w := range tc.want {
						ch := got.changes[i]
						msg := w.msg
						if noop {
							msg += " (noop)"
						}
						if ch.Property != w.prop || ch.Message != msg || ch.Name != w.name ||
							!reflect.DeepEqual(ch.Was, w.was) || !reflect.DeepEqual(ch.Is, w.is) || ch.Err != nil {
							t.Errorf("change %d = {%s %q %q %#v %#v %v}, want {%s %q %q %#v %#v}", i,
								ch.Property, ch.Message, ch.Name, ch.Was, ch.Is, ch.Err, w.prop, msg, w.name, w.was, w.is)
						}
						if wantVerbatim := w.prop != "ensure"; ch.DisplayVerbatim != wantVerbatim {
							t.Errorf("change %d DisplayVerbatim = %v", i, ch.DisplayVerbatim)
						}
					}
					wantWrites := 1
					if noop || len(tc.want) == 0 {
						wantWrites = 0
					}
					if len(h.tab.writes) != wantWrites {
						t.Errorf("writes = %q, want %d", h.tab.writes, wantWrites)
					}
				})
			}
		}
	}
}

// TestCronApplyDisplayVerbatim: the failure line's displays are the message's.
func TestCronApplyDisplayVerbatim(t *testing.T) {
	h := newCronHarness(t, "2.1.0", map[string]string{"root": seedJ})
	got := h.applyCrons(t, context.Background(), false,
		cronCatRes("j", map[string]any{"minute": []any{"1", "2"}}), cronCatRes("k", map[string]any{"environment": "A=1"}))
	if ch := got[0].changes[0]; ch.WasDisplay != "['15']" || ch.IsDisplay != "['1', '2']" {
		t.Errorf("minute displays = %q %q", ch.WasDisplay, ch.IsDisplay)
	}
	if ch := got[1].changes[0]; ch.WasDisplay != "['SHELL=/bin/sh', 'MAILTO=x']" || ch.IsDisplay != "A=1" {
		t.Errorf("environment displays = %q %q", ch.WasDisplay, ch.IsDisplay)
	}
}

// TestCronEnvironmentEmpty is spec 4.4 and 8 item 6 (M10): environment => []
// on a job with no environment lines is never in sync under 1.3.0 and in sync
// under 2.1.0.
func TestCronEnvironmentEmpty(t *testing.T) {
	r := cronCatRes("j", map[string]any{"environment": []any{}})
	h := newCronHarness(t, "1.3.0", map[string]string{"root": seedJ})
	got := h.applyCrons(t, context.Background(), false, r)[0]
	want := ral.Change{Property: "environment", Was: "absent", Is: []string{}, Message: "defined 'environment' as ",
		WasDisplay: "absent", IsDisplay: "", DisplayVerbatim: true}
	if got.err != nil || len(got.changes) != 1 || !reflect.DeepEqual(got.changes[0], want) {
		t.Errorf("1.3.0 = %#v, %v; want %#v", got.changes, got.err, want)
	}
	// The rewrite reads back the same way, so every run changes it again.
	h.tab.writes = nil
	again := h.applyCrons(t, context.Background(), false, r)[0]
	if len(again.changes) != 1 || len(h.tab.writes) != 1 {
		t.Errorf("1.3.0 rerun = %q, writes %d", messages(again.changes), len(h.tab.writes))
	}

	h = newCronHarness(t, "2.1.0", map[string]string{"root": seedJ})
	if got := h.applyCrons(t, context.Background(), false, r)[0]; got.err != nil || len(got.changes) != 0 || len(h.tab.writes) != 0 {
		t.Errorf("2.1.0 = %q, %v, writes %d; want in sync", messages(got.changes), got.err, len(h.tab.writes))
	}
}

// TestCronMinuteLeadingSpace is spec 8 item 17 (M12): under 2.1.0 ' 1' is kept,
// written, and reads back as ['1'], so it is never in sync.
func TestCronMinuteLeadingSpace(t *testing.T) {
	h := newCronHarness(t, "2.1.0", map[string]string{"root": "# Puppet Name: j\n1 * * * * /bin/j\n"})
	r := cronCatRes("j", map[string]any{"command": "/bin/j", "minute": " 1"})
	for run := 1; run <= 2; run++ {
		got := h.applyCrons(t, context.Background(), false, r)[0]
		if want := []string{"minute changed ['1'] to [' 1']"}; got.err != nil || !slices.Equal(messages(got.changes), want) {
			t.Fatalf("run %d = %q, %v; want %q", run, messages(got.changes), got.err, want)
		}
		if want := cronHeader0 + "# Puppet Name: j\n 1 * * * * /bin/j\n"; h.tab.tabs["root"] != want {
			t.Errorf("run %d wrote %q, want %q", run, h.tab.tabs["root"], want)
		}
	}
}

