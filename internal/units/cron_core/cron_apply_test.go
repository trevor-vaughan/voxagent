// scrubbing is the writer Task 10 hands newCron: each write passes through
// the run's current scrubber.
type scrubbing struct {
	w io.Writer
	s *redact.Scrubber
}

func (s scrubbing) Write(b []byte) (int, error) {
	if _, err := io.WriteString(s.w, s.s.Scrub(string(b))); err != nil {
		return 0, err
	}
	return len(b), nil
}

