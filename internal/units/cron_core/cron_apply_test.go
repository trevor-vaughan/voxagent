// TestCronReadErrorTarget is spec 6.4 (M1): a target whose read failed fails
// the flush that writes it, after the success event, as a FlushError; other
// targets are written.
func TestCronReadErrorTarget(t *testing.T) {
	h := newCronHarness(t, "2.1.0", nil)
	h.tab.replies["-u 1 -l"] = tabReply{code: 1, out: "crontab:  user `1' unknown\n"}
	got := h.applyCrons(t, context.Background(), false,
		cronCatRes("r1", map[string]any{"command": "/bin/r", "target": "1"}),
		cronCatRes("r2", map[string]any{"command": "/bin/r2"}),
		cronCatRes("r3", map[string]any{"ensure": "absent", "target": "1"}))
	if want := []string{"created"}; !slices.Equal(messages(got[0].changes), want) {
		t.Errorf("r1 changes = %q", messages(got[0].changes))
	}
	var fe *ral.FlushError
	const wantErr = "Failed to read 1's records when prefetching them. Reason: Could not read crontab for 1: Execution of 'crontab -u 1 -l' returned 1: crontab:  user `1' unknown"
	if !errors.As(got[0].err, &fe) || got[0].err.Error() != wantErr {
		t.Errorf("r1 err = %#v (%v), want FlushError %q", got[0].err, got[0].err, wantErr)
	}
	if got[1].err != nil || len(got[1].changes) != 1 {
		t.Errorf("r2 = %q, %v", messages(got[1].changes), got[1].err)
	}
	if got[2].err != nil || len(got[2].changes) != 0 {
		t.Errorf("r3 = %q, %v", messages(got[2].changes), got[2].err)
	}
	if want := []tabWrite{{"root", cronHeader0 + "# Puppet Name: r2\n* * * * * /bin/r2\n"}}; !slices.Equal(h.tab.writes, want) {
		t.Errorf("writes = %q, want %q", h.tab.writes, want)
	}
}

// TestCronUnknownWriteUser is spec 6.3: a target with no passwd entry reads as
