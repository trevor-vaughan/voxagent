// prov:<n> is lib/puppet/provider/cron/crontab.rb of puppetlabs-cron_core. The
// two releases differ in one line (prov:224, noted at prefetchHook), so the
// numbers are the same in both.

// Linux values package syscall does not export: <fcntl.h> AT_FDCWD and
// AT_EACCESS, <unistd.h> R_OK and W_OK. syscall.Faccessat honours AT_EACCESS
// through faccessat2, or emulates it from fstatat on older kernels, so the
// check uses the effective ids as Ruby's File.readable? and File.writable? do.
const (
	atFDCWD   = -100
	atEACCESS = 0x200
	rOK       = 4
	wOK       = 2
)

// The crontab grammar's patterns (prov:9-98). A grammar pattern sees one line,
// which holds no "\n", so RE2's text anchors equal Ruby's line anchors; \s is
// parsedfile.Space and \S parsedfile.NotSpace (spec 3.4).
var (
	commentLine     = regexp.MustCompile(`^` + parsedfile.Space + `*#`)                                                                                                                                   // prov:9
	puppetNameLine  = regexp.MustCompile(`Puppet Name: (.+)` + parsedfile.Space + `*$`)                                                                                                                   // prov:10
	blankLine       = regexp.MustCompile(`^` + parsedfile.Space + `*$`)                                                                                                                                   // prov:13
	environmentText = regexp.MustCompile(`^` + parsedfile.Space + `*\w+` + parsedfile.Space + `*=`)                                                                                                       // prov:15
	jobLine         = regexp.MustCompile(`^` + parsedfile.Space + `*(@\w+|` + strings.Repeat(parsedfile.NotSpace+`+`+parsedfile.Space+`+`, 4) + parsedfile.NotSpace + `+)` + parsedfile.Space + `+(.+)$`) // prov:34
	specialTime     = regexp.MustCompile(`@(` + parsedfile.NotSpace + `+)`)                                                                                                                               // prov:39
	fiveWordTime    = regexp.MustCompile(`(` + parsedfile.NotSpace + `+)` + strings.Repeat(parsedfile.Space+`+(`+parsedfile.NotSpace+`+)`, 4))                                                            // prov:47
	commaSeparator  = regexp.MustCompile(`,`)
	whitespaceRun   = regexp.MustCompile(parsedfile.Space + `+`)
)

// nativeHeader is the vixie cron header (prov:138-140), dropped from the text
// to write because cron adds a new one.
var nativeHeader = regexp.MustCompile(`(?s)# DO NOT EDIT THIS FILE.*?Cron version.*?vixie.*?\n`)

// tzLine is the line prov:239-251 hoists.
var tzLine = regexp.MustCompile(`(?m)^TZ=.+\n`)

// timeFields is TIME_FIELDS (prov:30) in file order, the order of a crontab
// line. cronTimeFields (cron.go) is the type's declaration order instead.
var timeFields = []string{"minute", "hour", "monthday", "month", "weekday"}

// cronResource adapts a munged Cron resource to parsedfile.Resource.
type cronResource struct{ p cronParams }

// Name implements parsedfile.Resource.
func (r cronResource) Name() string { return r.p.Name }

// Title implements parsedfile.Resource.
func (r cronResource) Title() string { return r.p.Title }

// ShouldTarget implements parsedfile.Resource: should(:target).
func (r cronResource) ShouldTarget() (string, bool) { return r.p.shouldText("target") }

// shouldText is a text property's should value.
func (p cronParams) shouldText(field string) (string, bool) {
	v, ok := p.Should[field]
	return v.S, ok && v.Kind == parsedfile.Str
}

// cronClass is the crontab provider as a parsedfile.Class (prov:4-309), one per
// run: the counter that names unmanaged jobs lives in its PrefetchHook.
//
// release picks 1.3.0's or 2.1.0's environment for a job with none (prov:224).
// providerTarget is the provider's default target, $USER when set (even empty),
// else root (prov:4); it is not the type's own `target` default
// (cron_params.go), which is the same by coincidence only. spoolDir is the
// directory prov:266-275 scans for crontabs. now is the clock of the header.
func cronClass(release string, providerTarget, spoolDir string, newFileType func(target string) (parsedfile.FileType, error), now func() time.Time) *parsedfile.Class {
	grammar, err := parsedfile.NewGrammar(
		parsedfile.LineType{Name: "comment", Text: true, Match: parsedfile.RE2(commentLine), PostParse: nameFromComment},
		parsedfile.LineType{Name: "blank", Text: true, Match: parsedfile.RE2(blankLine)},
		parsedfile.LineType{Name: "environment", Text: true, Match: parsedfile.RE2(environmentText)},
		parsedfile.LineType{
			Name: "crontab", Fields: []string{"time", "command"}, Match: parsedfile.RE2(jobLine),
			Absent: "*", PostParse: splitTime, ToLine: jobToLine,
		},
	)
	if err != nil {
		panic("cron grammar: " + err.Error()) // the definition is static
	}
	nameIndex := 0 // @name_index (prov:187), per run rather than per process
	return &parsedfile.Class{
		Name:          "crontab",
		TypeName:      "cron",
		Grammar:       grammar,
		DefaultTarget: providerTarget,
		FileType:      newFileType,
		Header:        cronHeader,
		NativeHeader:  nativeHeader,
		PrefetchHook: func(_ string, rs []*parsedfile.Record) ([]*parsedfile.Record, error) {
			return collapseNames(release, &nameIndex, rs)
		},
		ResourceForRecord: resourceForRecord,
		Adopt:             adopt,
		Targets: func(ctx context.Context, base []string) ([]string, error) {
			return withSpoolTargets(ctx, spoolDir, base)
		},
		ToFile: hoistTZ,
		Now:    now,
	}
}

// nameFromComment is the comment's post_parse (prov:9-11): a "Puppet Name: "
// anywhere in the line names the record, trailing spaces included.
func nameFromComment(r *parsedfile.Record) bool {
	if m := puppetNameLine.FindStringSubmatch(r.Line); m != nil {
		r.Fields["name"] = parsedfile.Value{Kind: parsedfile.Str, S: m[1]}
	}
	return true
}

// splitTime is the crontab's post_parse (prov:37-62). The line pattern allows
// only "@\w+" or five words as the time, and the two patterns here cover both,
// so Ruby's third branch (an error) is unreachable through a parsed line. It is
// kept as a false return, which fails the parse for that line, so that a time
// neither pattern matches cannot panic.
func splitTime(r *parsedfile.Record) bool {
	timeText := r.Fields["time"].S
	delete(r.Fields, "time")
	if m := specialTime.FindStringSubmatch(timeText); m != nil {
		for _, f := range timeFields {
			r.Fields[f] = parsedfile.Value{Kind: parsedfile.Absent}
		}
		r.Fields["special"] = parsedfile.Value{Kind: parsedfile.Str, S: m[1]}
		return true
	}
	m := fiveWordTime.FindStringSubmatch(timeText)
	if m == nil {
		return false
	}
	r.Fields["special"] = parsedfile.Value{Kind: parsedfile.Absent}
	for i, f := range timeFields {
		if m[i+1] == "*" {
			r.Fields[f] = parsedfile.Value{Kind: parsedfile.Absent}
		} else {
			r.Fields[f] = parsedfile.Value{Kind: parsedfile.List, L: parsedfile.Split(m[i+1], commaSeparator)}
		}
	}
	return true
}

// jobToLine is the crontab's to_line and pre_gen (prov:64-97): the name
// comment (never for an unmanaged record), the environment lines, then the
// special or the five time fields, and the command, one space apart. A nil or
// absent value is "*"; a list is joined with ",", so an empty one is an empty
// field. Values are written as they are, line breaks included (spec 4.5).
func jobToLine(r parsedfile.Record) (string, error) {
	var b strings.Builder
	if name := r.Fields["name"]; name.Kind == parsedfile.Str && !r.Flags["unmanaged"] {
		b.WriteString("# Puppet Name: " + name.S + "\n")
	}
	if env := r.Fields["environment"]; env.Kind == parsedfile.List {
		for _, line := range env.L {
			b.WriteString(line + "\n")
		}
	}
	var words []string
	if special := r.Fields["special"]; special.Kind == parsedfile.Str {
		words = []string{"@" + special.S}
	} else {
		for _, f := range timeFields {
			words = append(words, fieldText(r.Fields[f]))
		}
	}
	words = append(words, fieldText(r.Fields["command"]))
	b.WriteString(strings.Join(words, " "))
	return b.String(), nil
}

func fieldText(v parsedfile.Value) string {
	switch v.Kind {
	case parsedfile.Str:
		return v.S
	case parsedfile.List:
		return strings.Join(v.L, ",")
	}
	return "*"
}

// collapseNames is prefetch_hook (prov:190-237) for one target: it folds each
// "# Puppet Name:" comment and the environment lines after it into the next
// job, and names jobs that have no comment. nameIndex is the run's counter.
//
// envs is nil until a named comment starts it, and an empty envs stays non-nil
// after a job, so environment lines after a job with none attach to the next
// job or vanish (spec 8 item 4). A job with no environment lines gets Absent
// under 1.3.0 and the empty list under 2.1.0 (prov:224).
func collapseNames(release string, nameIndex *int, records []*parsedfile.Record) ([]*parsedfile.Record, error) {
	var name *string
	var envs []string
	collecting := false
	result := make([]*parsedfile.Record, 0, len(records))
	for _, rec := range records {
		switch rec.Type {
		case "comment":
			if n := rec.Fields["name"]; n.Kind == parsedfile.Str {
				name, collecting, envs = &n.S, true, nil
				continue
			}
		case "environment":
			if collecting {
				envs = append(envs, rec.Line)
				continue
			}
		case "blank":
		default:
			if name != nil {
				rec.Fields["name"] = parsedfile.Value{Kind: parsedfile.Str, S: *name}
				name = nil
			} else {
				// A command of exactly "*" equals the record type's absent text, so it
				// is :absent, and Ruby's gsub on it raises (measured M14a).
				if rec.Fields["command"].Kind == parsedfile.Absent {
					return nil, errors.New("undefined method `gsub' for :absent:Symbol")
				}
				command := rec.Fields["command"].S
				*nameIndex++
				rec.Fields["name"] = parsedfile.Value{Kind: parsedfile.Str, S: "unmanaged:" + whitespaceRun.ReplaceAllString(command, "_") + "-" + strconv.Itoa(*nameIndex)}
				rec.Flags["unmanaged"] = true
			}
			switch {
			case len(envs) > 0:
				rec.Fields["environment"] = parsedfile.Value{Kind: parsedfile.List, L: envs}
				envs, collecting = nil, false
			case release == release130:
				rec.Fields["environment"] = parsedfile.Value{Kind: parsedfile.Absent}
			default:
				rec.Fields["environment"] = parsedfile.Value{Kind: parsedfile.List, L: []string{}}
			}
		}
		result = append(result, rec)
	}
	return result, nil
}

// resourceForRecord is prov:121-126: the resource the engine would pick by
// name, kept only when the record sits in that resource's crontab, its target
// should or else its user should.
func resourceForRecord(rec *parsedfile.Record, byName map[string]parsedfile.Resource) (parsedfile.Resource, bool) {
	name := rec.Fields["name"]
	if name.Kind != parsedfile.Str {
		return nil, false
	}
	res, ok := byName[name.S]
	if !ok {
		return nil, false
	}
	p := res.(cronResource).p
	target, ok := p.shouldText("target")
	if !ok {
		target, ok = p.shouldText("user")
	}
	if !ok || rec.Target != target {
		return nil, false
	}
	return res, true
}

// adoptFields are the fields prov:159 compares after the command.
var adoptFields = []string{"minute", "hour", "monthday", "month", "weekday", "special"}

// adopt is prov:149-185: an unmanaged record is claimed by the first resource,
// in catalog order, with its target and command whose every set field equals
// the record's. A named record is never adopted (prov:152).
//
// A resource field that is `*` (Absent) matches a record's Absent; "special =>
// absent" never matches, as Ruby's value(:special) is nil there (type:449-467).
// A should list holds the text "absent" where Ruby holds :absent, so a record
// holding the literal word "absent" in a list would match a list with a
// non-leading `*` where Ruby's does not; cronie refuses such a field, so it
// cannot be installed (cron_params.go).
func adopt(rec *parsedfile.Record, matchers map[string]parsedfile.Resource, order []string) (parsedfile.Resource, bool) {
	if rec.Fields["name"].Kind == parsedfile.Str && !rec.Flags["unmanaged"] {
		return nil, false
	}
	for _, name := range order {
		res := matchers[name]
		if adoptable(rec, res.(cronResource).p) {
			return res, true
		}
	}
	return nil, false
}

func adoptable(rec *parsedfile.Record, p cronParams) bool {
	if target, ok := p.shouldText("target"); !ok || rec.Target != target {
		return false
	}
	// value(:command) is nil for a resource with no command, which equals no record.
	command, ok := p.shouldText("command")
	if got := rec.Fields["command"]; !ok || got.Kind != parsedfile.Str || got.S != command {
		return false
	}
	for _, f := range adoptFields {
		should, set := p.Should[f]
		if !set {
			continue // the resource does not manage the field, so any record matches
		}
		got, has := rec.Fields[f]
		if !has || got.Kind == parsedfile.Nil {
			return false
		}
		if should.Kind == parsedfile.Absent {
			if f == "special" {
				return false
			}
			if got.Kind == parsedfile.Absent {
				continue
			}
			should = parsedfile.Value{Kind: parsedfile.Str, S: "*"}
		}
		if should.Kind != got.Kind || should.S != got.S || !slices.Equal(should.L, got.L) {
			return false
		}
	}
	return true
}

// withSpoolTargets is targets and enumerate_crontabs (prov:290-309): base, then
// every regular file (after following links) in spoolDir that the effective uid
// can write and whose name does not start with ".keep_", in directory order,
// without repeats. It logs first, as Ruby does, and adds nothing when the
// directory is not readable. A directory that passes that check but cannot be
// listed (a regular file, M14b) is an error, as Dir.foreach raises: Ruby reports
// it from opendir as "<strerror> @ dir_initialize - <dir>", Go from readdir.
func withSpoolTargets(ctx context.Context, spoolDir string, base []string) ([]string, error) {
	runlog.Debugf(ctx, "Puppet", "looking for crontabs in %s", spoolDir)
	if syscall.Faccessat(atFDCWD, spoolDir, rOK, atEACCESS) != nil {
		return base, nil
	}
	dir, err := os.Open(spoolDir)
	if err != nil {
		return nil, errors.New(parsedfile.RubyErrno(err, "dir_initialize", spoolDir))
	}
	defer dir.Close()
	names, err := dir.Readdirnames(-1)
	if err != nil {
		return nil, errors.New(parsedfile.RubyErrno(err, "dir_initialize", spoolDir))
	}
	targets := slices.Clone(base)
	for _, name := range names {
		path := filepath.Join(spoolDir, name)
		fi, err := os.Stat(path)
		if err != nil || !fi.Mode().IsRegular() || strings.HasPrefix(name, ".keep_") {
			continue
		}
		if syscall.Faccessat(atFDCWD, path, wOK, atEACCESS) == nil && !slices.Contains(targets, name) {
			targets = append(targets, name)
		}
	}
	return targets, nil
}

// cronHeader is prov:130-135; Ruby interpolates Time#to_s of the local time.
func cronHeader(now time.Time) string {
	return "# HEADER: This file was autogenerated at " + now.Format("2006-01-02 15:04:05 -0700") + " by puppet.\n" +
		"# HEADER: While it can still be managed manually, it is definitely not recommended.\n" +
		"# HEADER: Note particularly that the comments starting with 'Puppet Name' should\n" +
		"# HEADER: not be deleted, as doing so could cause duplicate cron jobs.\n"
}

// hoistTZ is to_file's TZ handling (prov:239-251): the first "TZ=" line moves
// to the top. Its text is cut at its first literal occurrence, which may sit
// inside an earlier line (spec 8 item 13).
func hoistTZ(text string) string {
	tz := tzLine.FindString(text)
	if tz == "" {
		return text
	}
	return tz + strings.Replace(text, tz, "", 1)
}
