// runMounts applies a catalog of Mounts through the transaction, whose debug
// log is the report's.
func runMounts(t *testing.T, m Mount, rs ...catalog.Resource) *report.Report {
	t.Helper()
	rep := report.New("n", "production", false)
	ctx := runlog.WithLogger(context.Background(), runlog.New("debug", func(e report.LogEntry) { rep.AddLog(e) }, nil))
	cat := &catalog.Catalog{Resources: rs}
	tx := &transaction.Transaction{Registry: ral.NewRegistry(m)}
	g, err := transaction.BuildGraph(ctx, cat, tx.Registry)
	if err != nil {
		t.Fatal(err)
	}
	if err := tx.Run(ctx, cat, g, rep); err != nil {
		t.Fatal(err)
	}
	return rep
}

func logLines(rep *report.Report) []string {
	var out []string
	for _, l := range rep.Logs {
		if l.Level != "debug" {
			out = append(out, l.Level+" "+l.Source+": "+l.Message)
		}
	}
	return out
}

func contains(lines []string, want string) bool {
	for _, l := range lines {
		if l == want {
			return true
		}
	}
	return false
}

