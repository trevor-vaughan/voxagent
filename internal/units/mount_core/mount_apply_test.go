const mountBin, umountBin = "/usr/bin/mount", "/usr/bin/umount"

var fixedNow = func() time.Time { return time.Date(2026, 11, 23, 4, 42, 22, 0, time.UTC) }

// mountHeader is the header every write under fixedNow starts with (M4).
const mountHeader = "# HEADER: This file was autogenerated at 2026-11-23 04:42:22 +0000\n" +
	"# HEADER: by puppet.  While it can still be managed manually, it\n" +
	"# HEADER: is definitely not recommended.\n"

// cmdResult is one scripted command outcome.
type cmdResult struct {
	code int
	out  string
}

// fakeMount is a command.ShadowRunner scripting mount and umount: the listing
// (mount with no argument) prints listing, a command line in fail exits as
// scripted, every other command succeeds silently. Each call logs the debug
// line RunArgvWith logs (TestMountExecutingLineUnquoted pins the real one), so
// a test reads commands and Flushing lines in one order.
type fakeMount struct {
	listing string
	fail    map[string]cmdResult
	calls   [][]string
	opts    []command.ArgvOpts
}

func (f *fakeMount) Run(ctx context.Context, o command.ArgvOpts, name string, args ...string) (int, string, error) {
	argv := append([]string{name}, args...)
	f.calls = append(f.calls, argv)
	f.opts = append(f.opts, o)
	line := strings.Join(argv, " ")
	runlog.Debugf(ctx, "Puppet", "Executing: '%s'", line)
	if r, ok := f.fail[line]; ok {
		return r.code, r.out, nil
	}
	if name == mountBin && len(args) == 0 {
		return 0, f.listing, nil
	}
	return 0, "", nil
}

// mountHarness is a Mount over a fakeMount whose flat hooks record the paths
// they were called with, on fixedNow.
type mountHarness struct {
	m                 Mount
	run               *fakeMount
	backups, relabels []string
}

func newMountHarness(run *fakeMount) *mountHarness {
	mh := &mountHarness{run: run}
	mh.m = newMount("1.3.0", "UTF-8", mountBin, umountBin, run,
		func(_ context.Context, path string) error { mh.backups = append(mh.backups, path); return nil },
		func(_ context.Context, path string) error { mh.relabels = append(mh.relabels, path); return nil })
	mh.m.now = fixedNow
	return mh
}

// seedFstab writes text to a new fstab in a temp dir and returns its path.
func seedFstab(t *testing.T, text string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "fstab")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func readFstab(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// mountAt is a Mount resource on target.
func mountAt(title, target string, params map[string]any) catalog.Resource {
	p := map[string]any{"target": target}
	for k, v := range params {
		p[k] = v
	}
	return catalog.Resource{Type: "Mount", Title: title, Parameters: p}
}

// atResource is ctx carrying the sources the transaction gives r's Apply.
func atResource(ctx context.Context, r catalog.Resource) context.Context {
	return sources.WithSources(ctx, sources.Sources{Resource: "/Stage[main]/Main/" + r.Ref(), Ref: r.Ref()})
}

type mountOutcome struct {
	changes []ral.Change
	err     error
}

// apply prefetches rs and applies each in order, as the walk does, and returns
// the primed provider with the outcomes.
func (mh *mountHarness) apply(t *testing.T, ctx context.Context, noop bool, rs ...catalog.Resource) (Mount, []mountOutcome) {
	t.Helper()
	primed, err := mh.m.prefetch(ctx, rs)
	if err != nil {
		t.Fatalf("prefetch: %v", err)
	}
	var out []mountOutcome
	for _, r := range rs {
		changes, warnings, err := primed.Apply(atResource(ctx, r), r, noop)
		if len(warnings) != 0 {
			t.Errorf("%s: warnings %v", r.Ref(), warnings)
		}
		out = append(out, mountOutcome{changes, err})
	}
	return primed, out
}

// commandTrace is the Executing and Flushing debug lines, in order.
func commandTrace(entries []report.LogEntry) []string {
	var out []string
	for _, line := range raltest.LinesAt(entries, "Puppet") {
		if strings.HasPrefix(line, "Executing: ") || strings.HasPrefix(line, "Flushing ") {
			out = append(out, line)
		}
	}
	return out
}

// wantChange is a change's fields a test pins.
type wantChange struct {
	prop, msg, name string
	was, is         any
	wasShow, isShow string
}

func checkChanges(t *testing.T, ref string, got []ral.Change, want []wantChange, suffix string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%s: changes = %+v, want %d", ref, got, len(want))
	}
	for i, w := range want {
		g := got[i]
		if g.Property != w.prop || g.Message != w.msg+suffix || g.Name != w.name || g.Err != nil ||
			!reflect.DeepEqual(g.Was, w.was) || !reflect.DeepEqual(g.Is, w.is) {
			t.Errorf("%s: change %d = {%s %q %q %#v %#v %v}, want {%s %q %q %#v %#v}", ref, i,
				g.Property, g.Message, g.Name, g.Was, g.Is, g.Err, w.prop, w.msg+suffix, w.name, w.was, w.is)
		}
		if w.prop != "ensure" && (!g.DisplayVerbatim || g.WasDisplay != w.wasShow || g.IsDisplay != w.isShow) {
			t.Errorf("%s: change %d display = %v %q %q, want %q %q", ref, i, g.DisplayVerbatim, g.WasDisplay, g.IsDisplay, w.wasShow, w.isShow)
		}
	}
}

// The seeds of the M11 table: an fstab line for /mnt/x, and its line in the
// mount listing. Each fstab also holds a comment, which every write keeps.
const (
	keepLine   = "# keep\n"
	fstabLine  = "tmpfs\t/mnt/x\ttmpfs\tdefaults\t0\t0\n"
	listedLine = "tmpfs on /mnt/x type tmpfs (rw,relatime,seclabel,inode64)\n"
	listing    = "Executing: '/usr/bin/mount'"
	flushing   = "Flushing mount provider target "
	mountX     = "Executing: '/usr/bin/mount /mnt/x'"
	umountX    = "Executing: '/usr/bin/umount /mnt/x'"
)

// seedState is the fstab and the listing that give /mnt/x each current ensure.
func seedState(current string) (fstab, listed string) {
	switch current {
	case "ghost":
		return keepLine, listedLine
	case "unmounted":
		return keepLine + fstabLine, ""
	case "mounted":
		return keepLine + fstabLine, listedLine
	}
	return keepLine, ""
}

// TestMountEnsureTable is every row of spec 6.4's table and M11's, the in-sync
// rows included: the ensure message and event, the commands and flushes in
// order, the fstab after and the record's ensure after. Under noop every
// changing row reports the same change with " (noop)" and runs and writes
// nothing.
func TestMountEnsureTable(t *testing.T) {
	type row struct {
		should, current string
		msg, name       string
		acts            []string // after the listing; "F" is the Flushing line
		fstab           string   // "" = untouched
		after           string
	}
	written := mountHeader + keepLine + fstabLine
	emptied := mountHeader + keepLine
	rows := []row{
		{"defined", "absent", "defined 'ensure' as 'defined'", "mount_changed", []string{"F"}, written, "defined"},
		{"defined", "ghost", "ensure changed 'ghost' to 'defined'", "mount_changed", []string{"F"}, written, "defined"},
		{"defined", "mounted", "", "", nil, "", "mounted"},
		{"defined", "unmounted", "", "", nil, "", "unmounted"},
		{"unmounted", "absent", "defined 'ensure' as 'unmounted'", "mount_changed", []string{"F"}, written, "unmounted"},
		{"unmounted", "ghost", "ensure changed 'ghost' to 'unmounted'", "mount_changed", []string{"F", umountX}, written, "unmounted"},
		{"unmounted", "mounted", "ensure changed 'mounted' to 'unmounted'", "mount_changed", []string{umountX}, "", "unmounted"},
		{"unmounted", "unmounted", "", "", nil, "", "unmounted"},
		{"absent", "mounted", "undefined 'ensure' from 'mounted'", "mount_deleted", []string{umountX, "F"}, emptied, "absent"},
		{"absent", "ghost", "undefined 'ensure' from 'ghost'", "mount_deleted", []string{umountX, "F"}, emptied, "absent"},
		{"absent", "unmounted", "undefined 'ensure' from 'unmounted'", "mount_deleted", []string{"F"}, emptied, "absent"},
		{"absent", "absent", "", "", nil, "", "absent"},
		{"mounted", "absent", "defined 'ensure' as 'mounted'", "mount_mounted", []string{"F", mountX}, written, "mounted"},
		{"mounted", "ghost", "ensure changed 'ghost' to 'mounted'", "mount_mounted", []string{"F"}, written, "mounted"},
		{"mounted", "unmounted", "ensure changed 'unmounted' to 'mounted'", "mount_mounted", []string{mountX}, "", "mounted"},
		{"mounted", "mounted", "", "", nil, "", "mounted"},
	}
	for _, rw := range rows {
		for _, noop := range []bool{false, true} {
			t.Run(rw.should+"/from-"+rw.current+map[bool]string{true: "/noop"}[noop], func(t *testing.T) {
				seed, listed := seedState(rw.current)
				target := seedFstab(t, seed)
				mh := newMountHarness(&fakeMount{listing: listed})
				ctx, logs := raltest.DebugContext("debug")
				r := mountAt("/mnt/x", target, map[string]any{"ensure": rw.should, "device": "tmpfs", "fstype": "tmpfs", "options": "defaults"})
				primed, out := mh.apply(t, ctx, noop, r)
				if out[0].err != nil {
					t.Fatalf("Apply: %v", out[0].err)
				}
				suffix, acts, fstab, after := "", rw.acts, rw.fstab, rw.after
				if noop {
					suffix, acts, fstab, after = " (noop)", nil, "", rw.current
				}
				var want []wantChange
				if rw.msg != "" {
					want = []wantChange{{prop: "ensure", msg: rw.msg, name: rw.name, was: rw.current, is: rw.should}}
				}
				checkChanges(t, r.Ref(), out[0].changes, want, suffix)
				wantTrace := []string{listing}
				for _, a := range acts {
					if a == "F" {
						a = flushing + target
					}
					wantTrace = append(wantTrace, a)
				}
				if got := commandTrace(*logs); !reflect.DeepEqual(got, wantTrace) {
					t.Errorf("trace = %q, want %q", got, wantTrace)
				}
				if fstab == "" {
					fstab = seed
				}
				if got := readFstab(t, target); got != fstab {
					t.Errorf("fstab = %q, want %q", got, fstab)
				}
				if got := primed.state.Records["/mnt/x"].Ensure; got != after {
					t.Errorf("record ensure = %q, want %q", got, after)
				}
				nothing := raltest.LinesAt(*logs, "/Stage[main]/Main/Mount[/mnt/x]")
				if wantNothing := rw.should == "absent" && rw.current == "absent"; wantNothing != reflect.DeepEqual(nothing, []string{"Nothing to manage: no ensure and the resource doesn't exist"}) {
					t.Errorf("resource debug lines = %q", nothing)
				}
			})
		}
	}
}

// TestMountAbsentEmptiesFstab is M11's absent-from-mounted file: a write that
// leaves no record is the header and one empty line (M4, 174 bytes).
func TestMountAbsentEmptiesFstab(t *testing.T) {
	target := seedFstab(t, fstabLine)
	mh := newMountHarness(&fakeMount{listing: listedLine})
	_, out := mh.apply(t, context.Background(), false, mountAt("/mnt/x", target, map[string]any{"ensure": "absent"}))
	if out[0].err != nil || len(out[0].changes) != 1 {
		t.Fatalf("outcome = %+v", out[0])
	}
	if got := readFstab(t, target); got != mountHeader+"\n" || len(got) != 174 {
		t.Errorf("fstab = %q (%d bytes)", got, len(got))
	}
}

// TestMountNoEnsure is M11's no-ensure cases: with no record there is nothing
// to manage; a ghost counts as present, so every property is synced against
// the fresh record (pass and dump desired as Integer 0, target in sync: the
// getter of a record with no target is the should) and the fstab is written.
func TestMountNoEnsure(t *testing.T) {
	params := map[string]any{"device": "tmpfs", "fstype": "tmpfs", "options": "defaults"}
	t.Run("absent", func(t *testing.T) {
		target := seedFstab(t, keepLine)
		mh := newMountHarness(&fakeMount{})
		ctx, logs := raltest.DebugContext("debug")
		_, out := mh.apply(t, ctx, false, mountAt("/mnt/x", target, params))
		if out[0].err != nil || len(out[0].changes) != 0 {
			t.Errorf("outcome = %+v", out[0])
		}
		if got := raltest.LinesAt(*logs, "/Stage[main]/Main/Mount[/mnt/x]"); !reflect.DeepEqual(got, []string{"Nothing to manage: no ensure and the resource doesn't exist"}) {
			t.Errorf("debug = %q", got)
		}
		if got := readFstab(t, target); got != keepLine {
			t.Errorf("fstab = %q", got)
		}
	})
	t.Run("ghost", func(t *testing.T) {
		target := seedFstab(t, keepLine)
		mh := newMountHarness(&fakeMount{listing: listedLine})
		ctx, logs := raltest.DebugContext("debug")
		_, out := mh.apply(t, ctx, false, mountAt("/mnt/x", target, params))
		if out[0].err != nil {
			t.Fatal(out[0].err)
		}
		checkChanges(t, "ghost", out[0].changes, []wantChange{
			{prop: "device", msg: "defined 'device' as 'tmpfs'", was: "absent", is: "tmpfs", wasShow: "absent", isShow: "'tmpfs'"},
			{prop: "fstype", msg: "defined 'fstype' as 'tmpfs'", was: "absent", is: "tmpfs", wasShow: "absent", isShow: "'tmpfs'"},
			{prop: "options", msg: "defined 'options' as 'defaults'", was: "absent", is: "defaults", wasShow: "absent", isShow: "'defaults'"},
			{prop: "pass", msg: "defined 'pass' as 0", was: "absent", is: 0, wasShow: "absent", isShow: "0"},
			{prop: "dump", msg: "defined 'dump' as 0", was: "absent", is: 0, wasShow: "absent", isShow: "0"},
		}, "")
		if got, want := commandTrace(*logs), []string{listing, flushing + target}; !reflect.DeepEqual(got, want) {
			t.Errorf("trace = %q, want %q", got, want)
		}
		if got := readFstab(t, target); got != mountHeader+keepLine+fstabLine {
			t.Errorf("fstab = %q", got)
		}
	})
	t.Run("ghost/noop", func(t *testing.T) {
		target := seedFstab(t, keepLine)
		mh := newMountHarness(&fakeMount{listing: listedLine})
		_, out := mh.apply(t, context.Background(), true, mountAt("/mnt/x", target, params))
		if len(out[0].changes) != 5 || out[0].changes[0].Message != "defined 'device' as 'tmpfs' (noop)" || out[0].err != nil {
			t.Errorf("outcome = %+v", out[0])
		}
		if got := readFstab(t, target); got != keepLine || len(mh.backups) != 0 {
			t.Errorf("fstab = %q, backups %q", got, mh.backups)
		}
	})
}

// TestMountExistingLineDefaults is M12 and spec 8 items 20 and 21: a managed
// existing line's parsed dump and pass are Strings, the defaults Integer 0, so
// they are rewritten 0 0 (pass before dump); a 6+-field line's tail folded into
// pass displays double-quoted; \040 is a space in name and device.
func TestMountExistingLineDefaults(t *testing.T) {
	target := seedFstab(t, "/dev/a\\040b\t/mnt/p\\040q\text4\tdefaults\t1\t2\n"+
		"tmpfs /mnt/h tmpfs defaults  0  0  extra  more\n")
	mh := newMountHarness(&fakeMount{})
	_, out := mh.apply(t, context.Background(), false,
		mountAt("/mnt/p q", target, map[string]any{"options": "noatime"}),
		mountAt("/mnt/h", target, map[string]any{"fstype": "tmpfs"}))
	if out[0].err != nil || out[1].err != nil {
		t.Fatalf("errs %v %v", out[0].err, out[1].err)
	}
	checkChanges(t, "p q", out[0].changes, []wantChange{
		{prop: "options", msg: "options changed 'defaults' to 'noatime'", was: "defaults", is: "noatime", wasShow: "'defaults'", isShow: "'noatime'"},
		{prop: "pass", msg: "pass changed '2' to 0", was: "2", is: 0, wasShow: "'2'", isShow: "0"},
		{prop: "dump", msg: "dump changed '1' to 0", was: "1", is: 0, wasShow: "'1'", isShow: "0"},
	}, "")
	checkChanges(t, "h", out[1].changes, []wantChange{
		{prop: "pass", msg: `pass changed "0\textra\tmore" to 0`, was: "0\textra\tmore", is: 0, wasShow: `"0\textra\tmore"`, isShow: "0"},
	}, "")
	want := mountHeader + "/dev/a\\040b\t/mnt/p\\040q\text4\tnoatime\t0\t0\n" + "tmpfs\t/mnt/h\ttmpfs\tdefaults\t0\t0\n"
	if got := readFstab(t, target); got != want {
		t.Errorf("fstab = %q, want %q", got, want)
	}
}

// TestMountStringPassDump: a String should displays quoted and its desired
// value is the String; a String "0" is in sync with a parsed "0"; an Integer
