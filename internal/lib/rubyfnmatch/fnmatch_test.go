package rubyfnmatch

import (
	"encoding/base64"
	"encoding/json"
	"os"
	"testing"
)

type corpus struct {
	OpenVox string `json:"openvox"`
	Rows    []struct {
		PatternB64 string  `json:"pattern_b64"`
		NameB64    string  `json:"name_b64"`
		Match      *bool   `json:"match"`
		Error      *string `json:"error"`
	} `json:"rows"`
}

func loadCorpus(t *testing.T) corpus {
	t.Helper()
	data, err := os.ReadFile("testdata/fnmatch.json")
	if err != nil {
		t.Fatal(err)
	}
	var c corpus
	if err := json.Unmarshal(data, &c); err != nil {
		t.Fatal(err)
	}
	return c
}

func TestMatchMatchesRuby(t *testing.T) {
	c := loadCorpus(t)
	if len(c.Rows) < 600 {
		t.Fatalf("corpus has %d rows, want at least 600", len(c.Rows))
	}
	var errRows int
	for _, row := range c.Rows {
		pattern, err := base64.StdEncoding.DecodeString(row.PatternB64)
		if err != nil {
			t.Fatal(err)
		}
		name, err := base64.StdEncoding.DecodeString(row.NameB64)
		if err != nil {
			t.Fatal(err)
		}
		got, gotErr := Match(string(pattern), string(name))
		if row.Error != nil {
			errRows++
			if gotErr == nil || gotErr.Error() != *row.Error {
				t.Errorf("Match(%q, %q) error = %v, Ruby raised %q", pattern, name, gotErr, *row.Error)
			}
			continue
		}
		if row.Match == nil {
			t.Errorf("row %q, %q records neither a match nor an error", pattern, name)
			continue
		}
		if gotErr != nil {
			t.Errorf("Match(%q, %q) error = %v, Ruby answered %v", pattern, name, gotErr, *row.Match)
			continue
		}
		if got != *row.Match {
			t.Errorf("Match(%q, %q) = %v, Ruby says %v", pattern, name, got, *row.Match)
		}
	}
	if errRows == 0 {
		t.Error("corpus holds no raising rows; the error contract is untested")
	}
}

func TestMatchCorpusIsCurrent(t *testing.T) {
	if got := loadCorpus(t).OpenVox; got != "8.34.0" {
		t.Errorf("corpus generated by openvox %q, want 8.34.0; rerun testdata/gen.sh", got)
	}
}
